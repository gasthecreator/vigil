/**
 * Vigil Companion Service Worker (PWA Offline Cache & Sync)
 * Complies with Master Plan §6.8, §9.7, and Phase 6b.
 */

const CACHE_NAME = "vigil-companion-v1";
const STATIC_ASSETS = [
  "/companion",
  "/companion/symptoms",
  "/companion/share",
  "/manifest.json",
  "/globals.css",
];

// Install Event: Cache Core Application Shell
self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => {
      return cache.addAll(STATIC_ASSETS).catch((err) => {
        console.warn("Service Worker pre-caching non-fatal asset issue:", err);
      });
    })
  );
  self.skipWaiting();
});

// Activate Event: Clear Stale Caches
self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) => {
      return Promise.all(
        keys.filter((key) => key !== CACHE_NAME).map((key) => caches.delete(key))
      );
    })
  );
  self.clients.claim();
});

// Fetch Event: Network-First with Cache Fallback for HTML/CSS/JS
self.addEventListener("fetch", (event) => {
  // Only handle GET requests
  if (event.request.method !== "GET") return;

  const url = new URL(event.request.url);

  // For companion navigation requests: Network first, fall back to cache
  if (event.request.mode === "navigate" || url.pathname.startsWith("/companion")) {
    event.respondWith(
      fetch(event.request)
        .then((response) => {
          if (response && response.status === 200) {
            const copy = response.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(event.request, copy));
          }
          return response;
        })
        .catch(() => {
          return caches.match(event.request).then((cached) => {
            return cached || caches.match("/companion");
          });
        })
    );
    return;
  }

  // Stale-while-revalidate for static assets
  event.respondWith(
    caches.match(event.request).then((cachedResponse) => {
      const fetchPromise = fetch(event.request)
        .then((networkResponse) => {
          if (networkResponse && networkResponse.status === 200) {
            const copy = networkResponse.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(event.request, copy));
          }
          return networkResponse;
        })
        .catch(() => cachedResponse);

      return cachedResponse || fetchPromise;
    })
  );
});
