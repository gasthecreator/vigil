#!/usr/bin/env python3
"""scripts/generate_status.py

Generate docs/STATUS.md from living sources only:
  - docs/PROGRESS.md (phase ledger rows; Verdict column is quoted, never invented)
  - docs/safety/HAZARD_LOG.md (OPEN hazards)
  - docs/STUBS.md (open / claim-not-earned stubs)
  - .github/workflows/ci.yml (verification job names)

No maturity claims. No "complete" / "production-ready". Re-run and diff in CI.
"""

from __future__ import annotations

import argparse
import re
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STATUS_PATH = ROOT / "docs" / "STATUS.md"


def _table_rows(path: Path, id_pattern: str) -> list[list[str]]:
    rows: list[list[str]] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        s = line.strip()
        if not s.startswith("|"):
            continue
        parts = [p.strip() for p in s.split("|")[1:-1]]
        if not parts:
            continue
        cell0 = parts[0].replace("*", "").strip()
        if re.match(id_pattern, cell0):
            rows.append(parts)
    return rows


def parse_progress_phases() -> list[dict[str, str]]:
    path = ROOT / "docs" / "PROGRESS.md"
    out: list[dict[str, str]] = []
    for parts in _table_rows(path, r"^(P\d+[A-Za-z]?|T\d+[a-z]?)$"):
        if len(parts) < 6:
            continue
        # Skip separator-like rows
        if set(parts[0]) <= {"-", ":"}:
            continue
        out.append(
            {
                "phase": parts[0],
                "title": parts[1],
                "status": parts[2],
                "sha": parts[3],
                "report": parts[4],
                "verdict": parts[5],
            }
        )
    return out


def parse_open_hazards() -> list[dict[str, str]]:
    path = ROOT / "docs" / "safety" / "HAZARD_LOG.md"
    open_rows: list[dict[str, str]] = []
    for parts in _table_rows(path, r"^H\d+$"):
        if len(parts) < 7:
            continue
        status = parts[5].replace("*", "").strip()
        if status != "OPEN":
            continue
        open_rows.append(
            {
                "id": parts[0].replace("*", "").strip(),
                "hazard": parts[1],
                "severity": parts[3],
                "residual": parts[6][:240] + ("…" if len(parts[6]) > 240 else ""),
            }
        )
    return open_rows


def parse_open_stubs() -> list[dict[str, str]]:
    path = ROOT / "docs" / "STUBS.md"
    open_stubs: list[dict[str, str]] = []
    for parts in _table_rows(path, r"^S-\d+$"):
        if len(parts) < 6:
            continue
        plan = parts[4]
        gate = parts[5]
        # Closed stubs say "Closed" in plan/phase or "None (...)" in gate
        closed = plan.strip().lower().startswith("closed") or (
            gate.strip().lower().startswith("none") and "claim" not in parts[2].lower()
        )
        # Keep claim-not-earned / partially resolved / OPEN residual work
        text = " ".join(parts[1:6]).lower()
        if closed and "claim not earned" not in text and "partially" not in text and "not built" not in text:
            continue
        if "resolved" in parts[2].lower() and "claim not earned" not in parts[2].lower() and "partially" not in parts[2].lower():
            if "not built" not in parts[2].lower() and "not validated" not in parts[2].lower():
                continue
        open_stubs.append(
            {
                "id": parts[0],
                "component": parts[1][:80],
                "gate": gate[:120],
            }
        )
    return open_stubs


def parse_ci_jobs() -> list[str]:
    path = ROOT / ".github" / "workflows" / "ci.yml"
    jobs: list[str] = []
    in_jobs = False
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("jobs:"):
            in_jobs = True
            continue
        if not in_jobs:
            continue
        m = re.match(r"^  ([a-zA-Z0-9_-]+):\s*$", line)
        if m:
            jobs.append(m.group(1))
    return jobs


def render(phases: list[dict[str, str]], hazards: list[dict[str, str]], stubs: list[dict[str, str]], jobs: list[str]) -> str:
    now = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    lines: list[str] = [
        "# Vigil — STATUS (script-generated)",
        "",
        "> Generated by `scripts/generate_status.py`. Do not hand-edit.",
        f"> Generated at: `{now}` (UTC).",
        "> Sources: `docs/PROGRESS.md`, `docs/safety/HAZARD_LOG.md`, `docs/STUBS.md`, `.github/workflows/ci.yml`.",
        "> This file does **not** state maturity. Maturity is overseer-owned in `docs/PROGRESS.md`.",
        "",
        "## Phase ledger (executor status; Verdict quoted from PROGRESS)",
        "",
        "| Phase | Title | Status | Last verified SHA | Verdict (quoted) |",
        "|---|---|---|---|---|",
    ]
    for p in phases:
        lines.append(
            f"| {p['phase']} | {p['title']} | {p['status']} | {p['sha']} | {p['verdict']} |"
        )

    lines += [
        "",
        "## OPEN hazards",
        "",
        f"Count: **{len(hazards)}** (from `docs/safety/HAZARD_LOG.md`).",
        "",
        "| ID | Hazard (short) | Severity | Residual risk (truncated) |",
        "|---|---|---|---|",
    ]
    for h in hazards:
        lines.append(f"| {h['id']} | {h['hazard']} | {h['severity']} | {h['residual']} |")
    if not hazards:
        lines.append("| — | (none parsed as OPEN) | — | — |")

    lines += [
        "",
        "## Open / claim-not-earned stubs",
        "",
        f"Count: **{len(stubs)}** (rows that are not fully closed in `docs/STUBS.md`).",
        "",
        "| ID | Component | Gate item therefore NOT MET |",
        "|---|---|---|",
    ]
    for s in stubs:
        lines.append(f"| {s['id']} | {s['component']} | {s['gate']} |")
    if not stubs:
        lines.append("| — | (none) | — |")

    lines += [
        "",
        "## CI verification jobs (names only)",
        "",
        "From `.github/workflows/ci.yml`:",
        "",
    ]
    for j in jobs:
        lines.append(f"- `{j}`")

    lines += [
        "",
        "## How to regenerate",
        "",
        "```bash",
        "uv run python scripts/generate_status.py",
        "# or: uv run python scripts/generate_status.py --check   # exit 1 if docs/STATUS.md is stale",
        "```",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Regenerate in memory and exit 1 if docs/STATUS.md differs (CI freshness gate).",
    )
    args = parser.parse_args()

    phases = parse_progress_phases()
    hazards = parse_open_hazards()
    stubs = parse_open_stubs()
    jobs = parse_ci_jobs()
    body = render(phases, hazards, stubs, jobs)

    if args.check:
        if not STATUS_PATH.exists():
            print(f"❌ {STATUS_PATH} missing; run without --check to create it.", file=sys.stderr)
            return 1
        existing = STATUS_PATH.read_text(encoding="utf-8")
        # Compare ignoring the Generated-at timestamp line
        def _strip_ts(text: str) -> str:
            return re.sub(r"> Generated at: `[^`]+` \(UTC\)\.\n", "", text)

        if _strip_ts(existing) != _strip_ts(body):
            print("❌ docs/STATUS.md is stale relative to ledger/hazards/stubs/CI. Regenerate.", file=sys.stderr)
            return 1
        print("✅ docs/STATUS.md is fresh (timestamp ignored).")
        return 0

    STATUS_PATH.parent.mkdir(parents=True, exist_ok=True)
    STATUS_PATH.write_text(body, encoding="utf-8")
    print(f"✅ Wrote {STATUS_PATH} ({len(phases)} phases, {len(hazards)} OPEN hazards, {len(stubs)} open stubs, {len(jobs)} CI jobs).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
