#!/usr/bin/env python3
"""Generate a synthetic alert-burden simulation from vigil-sim and the deployed K2 implementation."""

from __future__ import annotations

import argparse
import json
import platform
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "packages/vigil-sim"))
sys.path.insert(0, str(ROOT / "packages/vigil-ml"))

from vigil_ml.k2 import SequentialDetector  # noqa: E402
from vigil_sim.generators import GeneratorType, get_generator  # noqa: E402


def run(seed: int, patients: int, duration_days: float, output_dir: Path, verify: bool = False) -> dict:
    cohort = get_generator(GeneratorType.G1_SMOOTH, seed=seed).generate_cohort(
        num_patients=patients, duration_days=duration_days, nominal_interval_days=90.0
    )
    frame = cohort.to_observations_dataframe()
    if "ca_15_3" not in frame or "observed_ca_15_3" not in frame:
        raise RuntimeError("Simulator cohort does not provide the expected masked CA 15-3 stream")

    evaluable = alerted = observations = 0
    for _, rows in frame.groupby("patient_id", sort=True):
        rows = rows.sort_values("day")
        stream = rows[rows["observed_ca_15_3"] == True]  # noqa: E712
        if stream.empty:
            continue
        detector = SequentialDetector()
        for row in stream.itertuples():
            detector.update(float(row.day), float(row.ca_15_3))
        evaluable += 1
        alerted += int(detector.alert)
        observations += len(stream)

    summary = {
        "title": "Synthetic alert-burden simulation",
        "data_status": "SYNTHETIC; generated by vigil-sim G1_SMOOTH",
        "claim_limit": "This measures K2 alert burden in one simulator world; it does not estimate clinical utility, sensitivity, or patient outcomes.",
        "command": "uv run python scripts/run_alert_fatigue_simulation.py",
        "machine": platform.platform(),
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "generator": "G1_SMOOTH",
        "seed": seed,
        "requested_patients": patients,
        "duration_days": duration_days,
        "nominal_interval_days": 90,
        "model": "vigil_ml.k2.SequentialDetector defaults (alpha_pt=0.05, sigma_log=0.12, burn_in=3)",
        "patients_with_observed_ca_15_3": evaluable,
        "patients_with_latched_alert": alerted,
        "fraction_with_latched_alert": alerted / evaluable if evaluable else None,
        "observed_ca_15_3_count": observations,
    }
    if verify:
        result_path = output_dir / "results.json"
        if not result_path.exists():
            raise RuntimeError(f"Missing committed simulation result: {result_path}")
        expected = json.loads(result_path.read_text(encoding="utf-8"))
        measured_keys = (
            "generator", "seed", "requested_patients", "duration_days", "nominal_interval_days", "model",
            "patients_with_observed_ca_15_3", "patients_with_latched_alert", "fraction_with_latched_alert",
            "observed_ca_15_3_count",
        )
        mismatched = [key for key in measured_keys if expected.get(key) != summary.get(key)]
        if mismatched:
            raise RuntimeError(f"Synthetic alert-burden result differs from committed values: {', '.join(mismatched)}")
        print(f"Verified simulator-written metrics against {result_path.relative_to(ROOT)}")
        return summary

    output_dir.mkdir(parents=True, exist_ok=True)
    (output_dir / "results.json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    lines = [
        "# Synthetic alert-burden simulation",
        "",
        f"**Data:** {summary['data_status']}",
        "",
        f"**Claim limit:** {summary['claim_limit']}",
        "",
        f"Generated by `{summary['command']}` on `{summary['machine']}` at `{summary['generated_at_utc']}`.",
        "",
        "## Measured run",
        "",
        f"- Generator / seed: `{summary['generator']}` / `{seed}`",
        f"- Requested patients / duration: {patients} / {duration_days:g} days",
        f"- Model: `{summary['model']}`",
        f"- Patients with observed CA 15-3: {evaluable}",
        f"- Patients with a latched alert: {alerted}",
        f"- Fraction with a latched alert: {summary['fraction_with_latched_alert']}",
        f"- Observed CA 15-3 values processed: {observations}",
        "",
        "This is one deterministic synthetic workload realization. It is not a measure of clinician fatigue, clinical performance, or a recommended alert threshold.",
    ]
    (output_dir / "REPORT.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return summary


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--seed", type=int, default=1624)
    parser.add_argument("--patients", type=int, default=250)
    parser.add_argument("--duration-days", type=float, default=730.0)
    parser.add_argument("--output-dir", type=Path, default=ROOT / "reports/usability/alert-fatigue")
    parser.add_argument("--verify", action="store_true", help="recompute and compare measured fields without rewriting the committed report")
    args = parser.parse_args()
    if args.patients < 1 or args.duration_days <= 0:
        parser.error("patients and duration-days must be positive")
    print(json.dumps(run(args.seed, args.patients, args.duration_days, args.output_dir, args.verify), indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
