#!/usr/bin/env python3
"""Write docs/ml/M4-WORKED-EXAMPLES.md from the M4 engine. Nothing in that file is typed by hand below the header.

Usage:
    uv run python scripts/m4_worked_examples.py          # (re)write the file
    uv run python scripts/m4_worked_examples.py --check  # exit 1 if the committed file differs

The prior, the date and the facilities are fixed here so the output is reproducible. The facilities are the
illustrative tier templates (no real facility): the table shows how the engine behaves, not what any real
facility offers.
"""

from __future__ import annotations

import argparse
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "packages" / "vigil-ml"))

from vigil_ml import m4_ladder as m4  # noqa: E402

OUT = ROOT / "docs" / "ml" / "M4-WORKED-EXAMPLES.md"
AS_OF = date(2026, 10, 18)
PRIOR = m4.Prior(value=0.15, lo=0.08, hi=0.25, provenance="worked example, not a patient")

HEADER = f"""# M4 test ladder: worked examples

> **Status: DRAFT-UNREVIEWED. Generated by `scripts/m4_worked_examples.py`; do not edit by hand.** Every number
> below is computed by `vigil_ml.m4_ladder` from `vigil_ml/registry/m4_test_evidence.json` and the illustrative
> facility templates in `vigil_ml/registry/m4_facility_templates.json`. The facilities are **placeholders, not
> real facilities** (every row is unverified, so every rung says availability must be confirmed). The prior is a
> worked example ({PRIOR.value:.2f}, interval {PRIOR.lo:.2f} to {PRIOR.hi:.2f}), not a patient. `as_of` is
> {AS_OF.isoformat()}. This is not clinical validation of any recommendation.

How to read a rung: *information gain* is the expected reduction, in bits, of the uncertainty about whether the
organ is involved (the interval runs from the lower to the upper accuracy corner and over the prior interval).
*Remaining after a negative* is the probability of involvement that is still left after a negative result,
as an interval. A negative result does not establish that the organ is free of metastasis. A wide
information-gain upper bound is a consequence of intervals that reach 1.0; the lower bound is the number the
ladder ranks on.

Limits that apply to every table:
- Accuracy comes from the studies in `docs/EVIDENCE.md` E20 to E22: liver from gastrointestinal primaries, bone from
  all cancers and from breast cancer (point estimates, no intervals), lung from one head-and-neck cohort. Rows
  that rely on a point estimate carry the assumed widening of plus or minus {m4.ASSUMED_HALFWIDTH:.2f}.
- Information gain per test does not model coverage (a whole-skeleton scan against a regional CT), radiation,
  contrast risk, patient preference or outcomes. The ladder is a transparent filter on cost, delay and
  information, not an instruction to order a test.
- Brain, bone plain radiograph and bone ALP/calcium trend have no accuracy source in the registry and are never
  ranked.
"""


def iv(i: m4.Interval, nd: int = 3) -> str:
    return f"{i.lo:.{nd}f} to {i.hi:.{nd}f}"


def render() -> str:
    ev = m4.load_evidence()
    templates = m4.load_facility_templates()
    out = [HEADER]
    for organ in m4.ORGANS:
        out.append(f"\n## {organ.capitalize()}\n")
        for fid, fac in templates.items():
            res = m4.recommend(
                organ, PRIOR, fac, AS_OF, evidence=ev, other_facilities=list(templates.values())
            )
            out.append(f"### {fid} ({fac.tier}): outcome `{res.outcome}`\n")
            if res.rungs:
                out.append(
                    "| Rung | Test | Price band | Days | Sensitivity | Specificity | Information gain (bits) "
                    "| Remaining after a negative | After a positive | Widening assumed | Evidence |"
                )
                out.append("|---|---|---|---|---|---|---|---|---|---|---|")
                for k, r in enumerate(res.rungs, 1):
                    out.append(
                        f"| {k} | {r.modality} | {r.price_band} | {r.turnaround_days} | {iv(r.sensitivity, 2)} "
                        f"| {iv(r.specificity, 2)} | {iv(r.information_gain_bits)} "
                        f"| {iv(r.residual_after_negative)} | {iv(r.probability_after_positive)} "
                        f"| {'yes' if r.assumed_widening else 'no'} | {', '.join(r.evidence_ids)} |"
                    )
                out.append("")
            if res.referrals:
                out.append(
                    "Referral options (nearest first): "
                    + "; ".join(
                        f"{x.facility_id} (first test {x.first_modality}, distance band {x.distance_band}, "
                        f"price band {x.price_band})"
                        for x in res.referrals
                    )
                    + "\n"
                )
            if res.skipped:
                out.append("Not ranked here:\n")
                for s in res.skipped:
                    out.append(f"- {s.modality}: `{s.reason_code}`. {s.reason}")
                out.append("")
            for n in res.notes:
                out.append(f"> {n}")
            out.append("")
    out.append("\n## Sensitivity of the chest radiograph result to the assumed widening\n")
    out.append(
        "| Assumed widening | Sensitivity | Specificity | Lower corner sensitivity + specificity | Shown informative |"
    )
    out.append("|---|---|---|---|---|")
    row = ev[("lung", "chest_radiograph")]
    for h in (0.0, 0.05, 0.10, 0.15):
        acc = m4.accuracy_range(row, h)
        out.append(
            f"| {h:.2f} | {iv(acc.se, 2)} | {iv(acc.sp, 2)} | {acc.se.lo + acc.sp.lo:.2f} "
            f"| {'yes' if acc.informative else 'no'} |"
        )
    out.append(
        "\nThe rule (lower corner sum below 1 means not shown informative) was fixed in "
        "`docs/ml/M4-CONTRACT.md` before this table existed. The table is here so that the dependence of the "
        "chest-radiograph result on the widening assumption is visible, not so that a widening can be chosen "
        "to obtain a preferred answer.\n"
    )
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} differs from the engine output; run scripts/m4_worked_examples.py")
            return 1
        print("M4 worked examples are up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
