#!/usr/bin/env python3
"""EXP-M7-001 Amendment 2: all-in harm / wait / disparity re-evaluation.

Reads ONLY experiments/EXP-M7-001/results.json (per-replication values written by the frozen run).
No simulation, no solver. Writes ALLIN_ANALYSIS.json and ALLIN_ANALYSIS.md.

Definitions (PREREG Amendment 2)
  all-in harm = mean_harm + unscheduled_harm  (per replication, per arm)
  paired bootstrap exactly as in the frozen run (run_study_m7_twin.paired_bootstrap_ci: percentile 95%, B=1000, seed 20261017)
  delta = baseline - research, positive = research better
Decision rule (fixed before computation): promotion candidate only if, in all 12 cells, the all-in CI lower bound > 0
against urgency AND FCFS, and wait / disparity are not significantly worse (CI upper bound of delta not < 0).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any, Dict

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
from run_study_m7_twin import paired_bootstrap_ci  # noqa: E402

EXP = ROOT / "experiments" / "EXP-M7-001"
RES = EXP / "results.json"
BASELINES = {"UrgencyHeuristic": "urgency", "FCFS": "fcfs", "HarmAwareProxy": "proxy"}


def analyse(res: Dict[str, Any]) -> Dict[str, Any]:
    out: Dict[str, Any] = {"source": "experiments/EXP-M7-001/results.json", "cells": {}}
    for key, cell in res["cells"].items():
        pr = cell["per_rep"]

        def arr(arm: str, fn) -> np.ndarray:
            return np.array([fn(r[arm]) for r in pr], dtype=float)

        allin = lambda a: a["mean_harm"] + a["unscheduled_harm"]  # noqa: E731
        row: Dict[str, Any] = {"means": {}, "delta_all_in": {}, "delta_wait_days": {}, "delta_disparity_days": {}}
        for arm in ("CPSAT_V2", *BASELINES):
            row["means"][arm] = {
                "mean_harm_headline": round(float(arr(arm, lambda a: a["mean_harm"]).mean()), 5),
                "unscheduled_harm": round(float(arr(arm, lambda a: a["unscheduled_harm"]).mean()), 5),
                "all_in_harm": round(float(arr(arm, allin).mean()), 5),
                "mean_wait_days": round(float(arr(arm, lambda a: a["mean_wait"]).mean()), 2),
                "disparity_days": round(float(arr(arm, lambda a: a["disparity"]).mean()), 3),
            }
        for arm, short in BASELINES.items():
            row["delta_all_in"][short] = list(paired_bootstrap_ci(arr(arm, allin) - arr("CPSAT_V2", allin)))
            row["delta_wait_days"][short] = list(paired_bootstrap_ci(arr(arm, lambda a: a["mean_wait"]) - arr("CPSAT_V2", lambda a: a["mean_wait"])))
            row["delta_disparity_days"][short] = list(paired_bootstrap_ci(arr(arm, lambda a: a["disparity"]) - arr("CPSAT_V2", lambda a: a["disparity"])))
        strongest = min(BASELINES.values(), key=lambda s: row["means"][[k for k, v in BASELINES.items() if v == s][0]]["all_in_harm"])
        row["strongest_baseline_all_in"] = strongest
        row["research_beats_urgency_and_fcfs_all_in"] = bool(row["delta_all_in"]["urgency"][1] > 0 and row["delta_all_in"]["fcfs"][1] > 0)
        row["research_significantly_worse_all_in_than"] = [s for s in BASELINES.values() if row["delta_all_in"][s][2] < 0]
        row["research_significantly_worse_wait_than"] = [s for s in BASELINES.values() if row["delta_wait_days"][s][2] < 0]
        row["research_significantly_worse_disparity_than"] = [s for s in BASELINES.values() if row["delta_disparity_days"][s][2] < 0]
        out["cells"][key] = row
    cells = out["cells"].values()
    cand = (
        all(c["research_beats_urgency_and_fcfs_all_in"] for c in cells)
        and not any(c["research_significantly_worse_wait_than"] or c["research_significantly_worse_disparity_than"] for c in cells)
    )
    out["decision"] = {
        "cells_beating_urgency_and_fcfs_all_in": sum(c["research_beats_urgency_and_fcfs_all_in"] for c in cells),
        "cells_where_research_is_significantly_worse_all_in_than_some_baseline": sum(bool(c["research_significantly_worse_all_in_than"]) for c in cells),
        "cells_where_research_is_significantly_worse_on_wait": sum(bool(c["research_significantly_worse_wait_than"]) for c in cells),
        "cells_where_research_is_significantly_worse_on_disparity": sum(bool(c["research_significantly_worse_disparity_than"]) for c in cells),
        "promotion_candidate": bool(cand),
        "verdict": "PROMOTION CANDIDATE" if cand else "NOT PROMOTED (all-in re-evaluation per PREREG Amendment 2)",
    }
    return out


def render(out: Dict[str, Any]) -> str:
    d = out["decision"]
    L = [
        "# EXP-M7-001 all-in re-evaluation (SYNTHETIC; PREREG Amendment 2)", "",
        "*Generated by `scripts/analyze_m7_cpsat_v2_allin.py` from `results.json` only. Exploratory/post-hoc relative to the frozen run; the decision rule was committed before this file existed.*", "",
        f"**Verdict: {d['verdict']}.**", "",
        f"- cells where research beats urgency AND FCFS on all-in harm (CI lower > 0): **{d['cells_beating_urgency_and_fcfs_all_in']}/12**",
        f"- cells where research is *significantly worse* all-in than at least one baseline: **{d['cells_where_research_is_significantly_worse_all_in_than_some_baseline']}/12**",
        f"- cells where research is significantly worse on mean wait: **{d['cells_where_research_is_significantly_worse_on_wait']}/12**; on disparity: **{d['cells_where_research_is_significantly_worse_on_disparity']}/12**",
        "", "All-in harm = headline `mean_harm` (wait + interruption) + `unscheduled_harm` (fractions never delivered within the 60-day horizon). Lower is better. Strongest baseline listed first.", "",
        "| cell | strongest baseline (all-in) | all-in: strongest baseline | urgency | FCFS | proxy | research | research - urgency [CI of urgency - research] | mean wait (d): urgency / research | disparity (d): urgency / research |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for k, c in out["cells"].items():
        m = c["means"]
        sb = c["strongest_baseline_all_in"]
        key = {"urgency": "UrgencyHeuristic", "fcfs": "FCFS", "proxy": "HarmAwareProxy"}[sb]
        du = c["delta_all_in"]["urgency"]
        L.append(
            f"| {k} | {sb} | {m[key]['all_in_harm']:.4f} | {m['UrgencyHeuristic']['all_in_harm']:.4f} | {m['FCFS']['all_in_harm']:.4f} | {m['HarmAwareProxy']['all_in_harm']:.4f} | "
            f"{m['CPSAT_V2']['all_in_harm']:.4f} | {du[0]:+.4f} [{du[1]:+.4f}, {du[2]:+.4f}] | "
            f"{m['UrgencyHeuristic']['mean_wait_days']:.1f} / {m['CPSAT_V2']['mean_wait_days']:.1f} | "
            f"{m['UrgencyHeuristic']['disparity_days']:.2f} / {m['CPSAT_V2']['disparity_days']:.2f} |"
        )
    L += ["", "Positive delta = research better. Negative = research worse. Full per-baseline intervals (all-in, wait, disparity) are in `ALLIN_ANALYSIS.json`.", ""]
    return "\n".join(L)


def main() -> int:
    res = json.loads(RES.read_text())
    out = analyse(res)
    (EXP / "ALLIN_ANALYSIS.json").write_text(json.dumps(out, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    (EXP / "ALLIN_ANALYSIS.md").write_text(render(out), encoding="utf-8")
    print(out["decision"]["verdict"])
    print(json.dumps({k: v for k, v in out["decision"].items() if k != "verdict"}, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
