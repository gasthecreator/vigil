#!/usr/bin/env python3
"""Generate the Diataxis index pages (ADRs, model cards, dataset cards, runbooks) so no document is orphaned (G-08).

Writes docs/diataxis/{adrs,model-cards,dataset-cards,runbooks}.md from the files on disk (first `# ` heading
as the title). ADR files are listed, never moved or edited (ADRs are immutable).

  uv run python scripts/generate_docs_indexes.py [--check | --seed-fail]
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
SETS = {
    "adrs": ("Architecture decision records", DOCS / "adr", "[0-9]*.md", "../adr/"),
    "model-cards": ("Model cards", DOCS / "models", "MODEL-CARD-*.md", "../models/"),
    "dataset-cards": ("Dataset cards", DOCS / "data", "DATASET-CARD-*.md", "../data/"),
    "runbooks": ("Runbooks", DOCS / "runbooks", "*.md", "../runbooks/"),
}


def title_of(path: Path) -> str:
    m = re.search(r"^#\s+(.+)$", path.read_text(encoding="utf-8"), re.M)
    return (m.group(1) if m else path.stem).strip()


def build(files: dict[str, list[Path]] | None = None) -> dict[str, str]:
    out = {}
    for key, (heading, folder, pattern, rel) in SETS.items():
        paths = sorted(folder.glob(pattern)) if files is None else files[key]
        lines = [
            f"# {heading}",
            "",
            "*Generated by `scripts/generate_docs_indexes.py`; CI fails if stale.*",
            "",
        ]
        lines += [f"- [{title_of(p)}]({rel}{p.name})" for p in paths]
        out[key] = "\n".join(lines) + "\n"
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--seed-fail", action="store_true")
    args = ap.parse_args()
    want = build()
    target = {k: DOCS / "diataxis" / f"{k}.md" for k in SETS}
    if args.check or args.seed_fail:
        have = {k: (p.read_text(encoding="utf-8") if p.exists() else "") for k, p in target.items()}
        if args.seed_fail:  # pretend a card was added after the index was generated
            have["model-cards"] = have["model-cards"].replace("- [", "- [x ", 1)
        stale = [k for k in SETS if have[k] != want[k]]
        if stale:
            print(
                f"❌ stale indexes (run scripts/generate_docs_indexes.py): {stale}", file=sys.stderr
            )
            return 1
        print("✅ docs indexes are fresh")
        return 0
    for k, p in target.items():
        p.write_text(want[k], encoding="utf-8")
    print(f"Wrote {len(target)} index pages under docs/diataxis/")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
