class BurstSheddingGenerator(BaseCohortGenerator):
    """
    G2 stress generator. Historical profiles use sampled persistent steps;
    `balanced_synthetic_core_v4` uses configured Poisson events with clearance.
    Both are synthetic assumptions, not fitted biological mechanisms.
    """

    def get_generator_type(self) -> GeneratorType:
        return GeneratorType.G2_BURST

    def simulate_longitudinal_trajectory(
        self,
        pt: PatientBaseline,
        visit_days: List[float],
    ) -> Tuple[List[Dict[str, float]], List[Dict[str, bool]], List[LatentCompartmentState]]:
        trajectories = []
        masks = []
        latents = []
        mechanics = self.generator_mechanics["g2"]

        t_rec = (
            pt.true_recurrence_day
            if pt.true_recurrence_event and pt.true_recurrence_day is not None
            else float("inf")
        )

        # Burst events occur at discrete times before clinical recurrence
        burst_times: List[float] = []
        shot_noise = mechanics["shot_noise"]
        if shot_noise is not None:
            end_day = max(visit_days, default=0.0)
            terminal_days = [end_day]
            if pt.true_recurrence_event and pt.true_recurrence_day is not None:
                terminal_days.append(max(0.0, pt.true_recurrence_day))
            else:
                terminal_days.append(0.0)
            if pt.competing_event_day is not None:
                terminal_days.append(max(0.0, pt.competing_event_day))
            if pt.administrative_censor_day is not None:
                terminal_days.append(max(0.0, pt.administrative_censor_day))
            exposure_days = min(terminal_days)
            event_times, event_amplitudes = draw_patient_shot_noise_trace(
                self.seed,
                pt.patient_id,
                exposure_days,
                shot_noise["event_rate_per_day"],
                shot_noise["burden_amplitude_mean"],
                shot_noise["burden_amplitude_coefficient_of_variation"],
            )
            total_mass_by_visit = np.asarray(
                [event_amplitudes[event_times <= day].sum() for day in visit_days],
                dtype=float,
            )
            event_count_by_visit = np.asarray(
                [np.count_nonzero(event_times <= day) for day in visit_days], dtype=int
            )
            ca153_by_visit = shot_noise_at_times(
                visit_days,
                event_times.tolist(),
                event_amplitudes * mechanics["ca153_per_burden"],
                shot_noise["ca153_clearance_rate_per_day"],
            )
            cea_by_visit = shot_noise_at_times(
                visit_days,
                event_times.tolist(),
                event_amplitudes * mechanics["cea_per_burden"],
                shot_noise["cea_clearance_rate_per_day"],
            )
        elif pt.true_recurrence_event and pt.true_recurrence_day is not None:
            burst_count = mechanics["burst_count_exclusive_range"]
            num_bursts = int(self.rng.integers(*burst_count))
            for _ in range(num_bursts):
                b_time = t_rec - float(
                    self.rng.uniform(*mechanics["days_before_recurrence_range"])
                )
                burst_times.append(b_time)
            burst_times.sort()
            event_count_by_visit = np.asarray(
                [sum(burst_day <= day for burst_day in burst_times) for day in visit_days],
                dtype=int,
            )
        else:
            event_count_by_visit = np.zeros(len(visit_days), dtype=int)

        for visit_index, d in enumerate(visit_days):
            if shot_noise is None:
                past_bursts = [bt for bt in burst_times if bt <= d]
                step_count = len(past_bursts)
                recent_window = mechanics["recent_burst_window_days"]
                recent_burst = any(0.0 <= (d - bt) <= recent_window for bt in past_bursts)
                total_mass = step_count * mechanics["burden_per_burst"]
                m_ca153 = total_mass * mechanics["ca153_per_burden"] + (
                    mechanics["ca153_recent_burst_increment"] if recent_burst else 0.0
                )
                m_cea = total_mass * mechanics["cea_per_burden"] + (
                    mechanics["cea_recent_burst_increment"] if recent_burst else 0.0
                )
            else:
                total_mass = float(total_mass_by_visit[visit_index])
                m_ca153 = float(ca153_by_visit[visit_index])
                m_cea = float(cea_by_visit[visit_index])
            b_bone = total_mass if pt.true_recurrence_site == TargetOrgan.BONE.value else 0.0
            b_liver = total_mass if pt.true_recurrence_site == TargetOrgan.LIVER.value else 0.0
            b_lung = total_mass if pt.true_recurrence_site == TargetOrgan.LUNG.value else 0.0
            b_brain = total_mass if pt.true_recurrence_site == TargetOrgan.BRAIN.value else 0.0
            b_loc = total_mass if pt.true_recurrence_site == TargetOrgan.BREAST.value else 0.0

            o_liver = b_liver * mechanics["liver_damage_per_liver_burden"]
            o_bone = b_bone * mechanics["bone_damage_per_bone_burden"]

            latent_st = LatentCompartmentState(
                patient_id=pt.patient_id,
                day=d,
                b_loc=b_loc,
                b_bone=b_bone,
                b_liver=b_liver,
                b_lung=b_lung,
                b_brain=b_brain,
                m_ca153=m_ca153,
                m_cea=m_cea,
                o_liver=o_liver,
                o_bone=o_bone,
                o_renal=0.0,
                is_indolent=pt.is_indolent,
                mechanism_event_count=int(event_count_by_visit[visit_index]),
            )
            latents.append(latent_st)

            vals: Dict[str, float] = {}
            obs_mask: Dict[str, bool] = {}

            for code, base_val in pt.base_marker_levels.items():
                analyte = ANALYTE_REGISTRY[code]
                sigma_i = analyte.biological_variation.cv_i / 100.0
                bio_noise = self.rng.normal(0.0, sigma_i)
                current_val = base_val * (1.0 + bio_noise)
                if mechanics["apply_facility_lab_effects"]:
                    current_val = (
                        current_val * pt.lab_scales.get(code, 1.0)
                        + base_val * pt.lab_offsets.get(code, 0.0)
                    )

                if code in ["ca_15_3", "ca_27_29"]:
                    current_val += m_ca153
                elif code == "cea":
                    current_val += m_cea
                elif code in ["alt", "ast"] and pt.true_recurrence_site == TargetOrgan.LIVER.value:
                    current_val += o_liver * mechanics["liver_enzyme_per_damage"]
                elif code == "alp" and pt.true_recurrence_site == TargetOrgan.BONE.value:
                    current_val += o_bone * mechanics["alp_per_bone_damage"]

                p = analyte.plausibility
                vals[code] = float(np.clip(current_val, p.physiological_min, p.physiological_max))
                skip_probability = self.measurement_skip_probability(pt, code)
                obs_mask[code] = bool(self.rng.random() > skip_probability)

            trajectories.append(vals)
            masks.append(obs_mask)

        return trajectories, masks, latents


# ==============================================================================
# Generator G3: Heavy-Tailed Noise & Pre-Analytical Errors
# ==============================================================================


class HeavyTailedNoiseGenerator(BaseCohortGenerator):
    """
    Generator G3: Heavy-tailed Student-t measurement noise, inter-lab offsets, and pre-analytical error injection.
    - Heavy-tailed Student-t (nu=3) noise.
    - Pre-analytical error injection (haemolysis, saline dilution).
    - Informative missingness.
    """

    def get_generator_type(self) -> GeneratorType:
        return GeneratorType.G3_NOISE

    def simulate_longitudinal_trajectory(
        self,
        pt: PatientBaseline,
        visit_days: List[float],
    ) -> Tuple[List[Dict[str, float]], List[Dict[str, bool]], List[LatentCompartmentState]]:
        trajectories = []
        masks = []
        latents = []
        mechanics = self.generator_mechanics["g3"]

        t_rec = (
            pt.true_recurrence_day
            if pt.true_recurrence_event and pt.true_recurrence_day is not None
            else float("inf")
        )

        for d in visit_days:
            # Check for injected pre-analytical error
            preanalytical_error: Optional[str] = None
            roll = self.rng.random()
            haemolysis_probability = mechanics["haemolysis_probability"]
            dilution_probability = mechanics["sample_dilution_probability"]
            if roll < haemolysis_probability:
                preanalytical_error = "haemolysis"
            elif roll < haemolysis_probability + dilution_probability:
                preanalytical_error = "sample_dilution"

            days_to_rec = t_rec - d
            active_signal_days = mechanics["active_signal_days"]
            is_active = days_to_rec <= active_signal_days

            # Signal strength
            if mechanics["saturate_signal"]:
                sig = (
                    float(np.clip((active_signal_days - days_to_rec) / active_signal_days, 0.0, 1.0))
                    if is_active
                    else 0.0
                )
            else:
                # Preserve historical-profile data semantics; core_v3 opts into the corrected bound.
                sig = max(0.0, (active_signal_days - days_to_rec) / active_signal_days) if is_active else 0.0
            mass = sig * mechanics["burden_at_full_signal"]

            b_bone = mass if pt.true_recurrence_site == TargetOrgan.BONE.value else 0.0
            b_liver = mass if pt.true_recurrence_site == TargetOrgan.LIVER.value else 0.0
            b_lung = mass if pt.true_recurrence_site == TargetOrgan.LUNG.value else 0.0
            b_brain = mass if pt.true_recurrence_site == TargetOrgan.BRAIN.value else 0.0
            b_loc = mass if pt.true_recurrence_site == TargetOrgan.BREAST.value else 0.0

            latent_st = LatentCompartmentState(
                patient_id=pt.patient_id,
                day=d,
                b_loc=b_loc,
                b_bone=b_bone,
                b_liver=b_liver,
                b_lung=b_lung,
                b_brain=b_brain,
                m_ca153=mass * mechanics["ca153_per_burden"],
                m_cea=mass * mechanics["cea_per_burden"],
                o_liver=b_liver * mechanics["liver_damage_per_liver_burden"],
                o_bone=b_bone * mechanics["bone_damage_per_bone_burden"],
                o_renal=0.0,
                is_indolent=pt.is_indolent,
            )
            latents.append(latent_st)

            vals: Dict[str, Any] = {}
            obs_mask: Dict[str, bool] = {}

            for code, base_val in pt.base_marker_levels.items():
                analyte = ANALYTE_REGISTRY[code]
                sigma_i = analyte.biological_variation.cv_i / 100.0

                # Heavy-tailed Student-t noise (df=3)
                t_noise = float(
                    self.rng.standard_t(df=mechanics["student_t_degrees_freedom"])
                    * (sigma_i * mechanics["student_t_noise_scale"])
                )
                offset = pt.lab_offsets.get(code, 0.0)
                if mechanics["apply_facility_lab_effects"]:
                    current_val = (
                        base_val * (1.0 + t_noise) * pt.lab_scales.get(code, 1.0)
                        + base_val * offset
                    )
                else:
                    current_val = base_val * (1.0 + offset + t_noise)

                # True recurrence signal
                if is_active:
                    if code == "ca_15_3":
                        current_val += sig * mechanics["ca153_signal_increment"]
                    elif code == "alt" and pt.true_recurrence_site == TargetOrgan.LIVER.value:
                        current_val += sig * mechanics["alt_liver_signal_increment"]
                    elif code == "alp" and pt.true_recurrence_site == TargetOrgan.BONE.value:
                        current_val += sig * mechanics["alp_bone_signal_increment"]

                # Pre-analytical error injection
                if preanalytical_error == "haemolysis":
                    # Rupture of RBCs spikes AST and LDH
                    if code == "ast":
                        current_val *= float(
                            self.rng.uniform(*mechanics["haemolysis_ast_multiplier"])
                        )
                    elif code == "ldh":
                        current_val *= float(
                            self.rng.uniform(*mechanics["haemolysis_ldh_multiplier"])
                        )
                elif preanalytical_error == "sample_dilution":
                    # IV fluid dilution reduces concentrations by 25-40%
                    current_val *= float(
                        self.rng.uniform(*mechanics["sample_dilution_multiplier"])
                    )

                p = analyte.plausibility
                vals[code] = float(np.clip(current_val, p.physiological_min, p.physiological_max))
                skip_probability = self.measurement_skip_probability(pt, code)
                obs_mask[code] = bool(self.rng.random() > skip_probability)

            if preanalytical_error:
                vals["_preanalytical_error"] = preanalytical_error

            trajectories.append(vals)
            masks.append(obs_mask)

        return trajectories, masks, latents


def get_generator(
    generator_type: GeneratorType | str,
    seed: int = 42,
    population_config: Optional[Dict[str, Any]] = None,
) -> BaseCohortGenerator:
    """Factory function for retrieving a cohort generator by type."""
    t = GeneratorType(generator_type)
    if t == GeneratorType.G1_SMOOTH:
        return ContinuousSecretionGenerator(seed=seed, population_config=population_config)
    elif t == GeneratorType.G2_BURST:
        return BurstSheddingGenerator(seed=seed, population_config=population_config)
    elif t == GeneratorType.G3_NOISE:
        return HeavyTailedNoiseGenerator(seed=seed, population_config=population_config)
    raise ValueError(f"Unknown generator type: {generator_type}")
