    def evaluate_verification_mechanism(
        self,
        pt: PatientBaseline,
        day: float,
        symptoms: Dict[str, int],
        analytes: Dict[str, float],
        latent_state: LatentCompartmentState,
    ) -> Tuple[bool, Optional[bool], float]:
        """
        Partial verification mechanism (ML_PROGRAM §4.2, H-D):
        Imaging (CT/US/bone scan) is triggered primarily by:
        1. Moderate/severe symptoms (Grade >= 2)
        2. Substantial marker elevation (CA 15-3 >= 60 [iU]/mL)
        3. Scheduled surveillance protocol (occasional baseline verification ~15%)
        """
        # Baseline probability of routine surveillance imaging
        verification = self.population_config.get("verification")
        if verification:
            p_image = float(verification["routine_imaging_probability"]) / pt.out_of_pocket_delay_factor
            symptom_thresholds = verification["symptom_grade_thresholds"]
            symptom_increments = verification["symptom_probability_increments"]
            marker_thresholds = verification["marker_thresholds"]
            marker_increments = verification["marker_probability_increments"]
            max_probability = float(verification["maximum_imaging_probability"])
        else:
            p_image = 0.08 / pt.out_of_pocket_delay_factor
            symptom_thresholds, symptom_increments = [2, 3], [0.40, 0.70]
            marker_thresholds, marker_increments = [35.0, 75.0], [0.30, 0.65]
            max_probability = 0.95

        # Symptoms dramatically raise clinical suspicion
        max_symptom = max(symptoms.values()) if symptoms else 0
        if max_symptom >= symptom_thresholds[1]:
            p_image += symptom_increments[1]
        elif max_symptom >= symptom_thresholds[0]:
            p_image += symptom_increments[0]

        # High tumour marker triggers imaging workup
        ca153_val = analytes.get("ca_15_3", 0.0)
        if ca153_val >= marker_thresholds[1]:
            p_image += marker_increments[1]
        elif ca153_val >= marker_thresholds[0]:
            p_image += marker_increments[0]

        p_image = min(max_probability, p_image)
        performed = bool(self.rng.random() < p_image)

        # If imaging is performed and total metastatic burden exceeds radiological resolution threshold (burden >= 12.0)
        total_burden = (
            latent_state.b_bone
            + latent_state.b_liver
            + latent_state.b_lung
            + latent_state.b_brain
            + latent_state.b_loc
        )
        burden_threshold = (
            float(verification["visible_burden_threshold"]) if verification else 12.0
        )
        visible_recurrence = pt.true_recurrence_event and total_burden >= burden_threshold
        result: Optional[bool] = None
        if performed:
            if verification:
                probability_positive = (
                    float(verification["sensitivity"])
                    if visible_recurrence
                    else 1.0 - float(verification["specificity"])
                )
                result = bool(self.rng.random() < probability_positive)
            else:
                result = bool(visible_recurrence)
            # A positive result alone is a screening finding; only a visible
            # latent recurrence can become the synthetic confirmed-diagnosis label.
            if result and visible_recurrence and not pt.observed_recurrence_event:
                pt.observed_recurrence_event = True
                pt.observed_recurrence_day = day
                pt.observed_recurrence_site = pt.true_recurrence_site

        return performed, result, p_image

    def generate_cohort(
        self,
        num_patients: int = 100,
        duration_days: float = 730.0,
        nominal_interval_days: float = 90.0,
    ) -> CohortDataset:
        """Generates a complete longitudinal cohort dataset."""
        patients: List[PatientBaseline] = []
        observations: List[LongitudinalObservation] = []
        latent_states: List[LatentCompartmentState] = []

        start_date = datetime(2024, 1, 1, 8, 0, 0, tzinfo=timezone.utc)

        for i in range(1, num_patients + 1):
            pt = self.sample_baseline(i)
            pt.administrative_censor_day = float(duration_days)
            patients.append(pt)

            # Generate irregular visit process with informative missingness and out-of-pocket delays
            visit_days = []
            curr_day = float(self.rng.uniform(0.0, 15.0))
            while curr_day < duration_days:
                # Stop follow-up if competing event (death/lost) occurred
                if pt.competing_event_day is not None and curr_day >= pt.competing_event_day:
                    break
                visit_days.append(curr_day)

                # Next scheduled visit: Gamma distribution modified by out-of-pocket friction
                visit_gamma = self.population_config.get("visit_interval_gamma", {"shape": 4.0, "scale": 0.25})
                interval = nominal_interval_days * float(
                    self.rng.gamma(shape=visit_gamma["shape"], scale=visit_gamma["scale"])
                )
                interval *= pt.out_of_pocket_delay_factor
                curr_day += interval

            # If patient is recurrent, visits taper off ~90 days after clinical confirmation as they shift to acute oncology
            if pt.observed_recurrence_event and pt.observed_recurrence_day is not None:
                visit_days = [d for d in visit_days if d <= (pt.observed_recurrence_day + 90.0)]

            if not visit_days:
                visit_days = [0.0]

            trajectories, obs_masks, pt_latents = self.simulate_longitudinal_trajectory(
                pt, visit_days
            )
            latent_states.extend(pt_latents)

            for d, analyte_vals, mask, latent_st in zip(
                visit_days, trajectories, obs_masks, pt_latents
            ):
                if (
                    pt.observed_recurrence_event
                    and pt.observed_recurrence_day is not None
                    and d > pt.observed_recurrence_day + 90.0
                ):
                    break
                obs_id = f"OBS-{pt.patient_id}-{int(d):04d}"
                date_drawn = (start_date + timedelta(days=float(d))).isoformat()
                symptoms = self.generate_symptoms(pt, d, latent_st)

                # Preanalytical error tag if present
                error_value = analyte_vals.pop("_preanalytical_error", None)
                error_type = error_value if isinstance(error_value, str) else None

                # Verification mechanism
                imaging_done, imaging_result, imaging_probability = self.evaluate_verification_mechanism(
                    pt, d, symptoms, analyte_vals, latent_st
                )

                obs = LongitudinalObservation(
                    observation_id=obs_id,
                    patient_id=pt.patient_id,
                    day=float(d),
                    date_drawn=date_drawn,
                    analytes=analyte_vals,
                    observed_mask=mask,
                    symptoms=symptoms,
                    imaging_performed=imaging_done,
                    preanalytical_error=error_type,
                    is_synthetic=True,
                    imaging_result=imaging_result,
                    imaging_probability=imaging_probability,
                    facility_id=pt.facility_id,
                    treatment_active=latent_st.treatment_active,
                )
                observations.append(obs)

        return CohortDataset(
            patients=patients,
            observations=observations,
            latent_states=latent_states,
            generator_type=self.get_generator_type(),
            seed=self.seed,
        )


