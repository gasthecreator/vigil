def _is_finite_number(
    value: object,
) -> TypeGuard[int | float | np.integer[Any] | np.floating[Any]]:
    if not isinstance(value, (int, float, np.integer, np.floating)):
        return False
    if isinstance(value, (bool, np.bool_)):
        return False
    return bool(np.isfinite(value))


def _is_finite_nonnegative_number(value: object) -> bool:
    if not _is_finite_number(value):
        return False
    return bool(value >= 0)


@dataclass
class LatentCompartmentState:
    """Ground-truth latent biological state at time t (exported for recovery/identifiability tests)."""

    patient_id: str
    day: float
    b_loc: float  # Locoregional tumor burden (arbitrary cell mass units)
    b_bone: float  # Bone metastatic burden
    b_liver: float  # Liver metastatic burden
    b_lung: float  # Lung metastatic burden
    b_brain: float  # Brain metastatic burden
    m_ca153: float  # Synthetic CA 15-3 increment generated by the selected stress model
    m_cea: float  # Synthetic CEA increment generated by the selected stress model
    o_liver: float  # Hepatic damage/parenchymal infiltration state
    o_bone: float  # Bone turnover/osteolytic activity state
    o_renal: float  # Renal impairment state
    is_indolent: bool = False
    treatment_active: Optional[str] = None
    mechanism_event_count: int = 0


@dataclass
class PatientBaseline:
    patient_id: str
    age: float
    stage: PresentationStage
    subtype: BreastCancerSubtype
    er_status: bool
    pr_status: bool
    her2_status: bool

    # Ground-truth latent disease parameters
    true_recurrence_event: bool
    true_recurrence_day: Optional[float]
    true_recurrence_site: Optional[str]
    is_indolent: bool

    # Clinical observed event parameters (partial verification bias)
    observed_recurrence_event: bool
    observed_recurrence_day: Optional[float]
    observed_recurrence_site: Optional[str]

    # Competing risks
    competing_event: Optional[str]  # configured competing cause or loss-to-follow-up label
    competing_event_day: Optional[float]

    # Facility and economics
    generator_id: str
    facility_id: str
    out_of_pocket_delay_factor: float
    lab_offsets: Dict[str, float] = field(default_factory=dict)
    lab_scales: Dict[str, float] = field(default_factory=dict)
    base_marker_levels: Dict[str, float] = field(default_factory=dict)
    administrative_censor_day: Optional[float] = None


@dataclass
class LongitudinalObservation:
    observation_id: str
    patient_id: str
    day: float
    date_drawn: str
    analytes: Dict[str, float]
    observed_mask: Dict[str, bool]  # True = measured, False = missing (MNAR)
    symptoms: Dict[str, int]  # Grade 0 to 4
    imaging_performed: bool  # Verification mechanism flag
    preanalytical_error: Optional[str] = None
    is_synthetic: bool = True
    imaging_result: Optional[bool] = None
    imaging_probability: Optional[float] = None
    facility_id: Optional[str] = None
    treatment_active: Optional[str] = None


@dataclass
class CohortDataset:
    patients: List[PatientBaseline]
    observations: List[LongitudinalObservation]
    latent_states: List[LatentCompartmentState]
    generator_type: GeneratorType
    seed: int

    def to_observations_dataframe(self) -> pd.DataFrame:
        """Flattens longitudinal observations into a standard clinical observation dataframe.

        Hidden simulator truth is available only through the separate explicit
        ``to_latent_states_dataframe`` export, never through clinical observations.
        """
        rows = []
        for obs in self.observations:
            row = {
                "observation_id": obs.observation_id,
                "patient_id": obs.patient_id,
                "day": obs.day,
                "date_drawn": obs.date_drawn,
                "imaging_performed": obs.imaging_performed,
                "imaging_result": obs.imaging_result,
                "imaging_probability": obs.imaging_probability,
                "facility_id": obs.facility_id,
                "treatment_active": obs.treatment_active,
                "preanalytical_error": obs.preanalytical_error,
                "is_synthetic": obs.is_synthetic,
            }
            # Analytes and observation masks
            for k, v in obs.analytes.items():
                is_observed = bool(obs.observed_mask.get(k, True))
                row[f"observed_{k}"] = is_observed
                row[k] = v if is_observed else np.nan
            # Symptoms
            for s, g in obs.symptoms.items():
                row[f"symptom_{s}"] = g
            rows.append(row)
        return pd.DataFrame(rows)

    def to_patients_dataframe(self) -> pd.DataFrame:
        """Returns the patient baseline and ground truth clinical event registry."""
        rows = []
        for p in self.patients:
            rows.append(
                {
                    "patient_id": p.patient_id,
                    "age": p.age,
                    "stage": p.stage.value,
                    "subtype": p.subtype.value,
                    "er_status": p.er_status,
                    "pr_status": p.pr_status,
                    "her2_status": p.her2_status,
                    "true_recurrence_event": p.true_recurrence_event,
                    "true_recurrence_day": p.true_recurrence_day,
                    "true_recurrence_site": p.true_recurrence_site,
                    "is_indolent": p.is_indolent,
                    "observed_recurrence_event": p.observed_recurrence_event,
                    "observed_recurrence_day": p.observed_recurrence_day,
                    "observed_recurrence_site": p.observed_recurrence_site,
                    "competing_event": p.competing_event,
                    "competing_event_day": p.competing_event_day,
                    "administrative_censor_day": p.administrative_censor_day,
                    "generator_id": p.generator_id,
                    "facility_id": p.facility_id,
                    "out_of_pocket_delay_factor": p.out_of_pocket_delay_factor,
                }
            )
        return pd.DataFrame(rows)

    def to_latent_states_dataframe(self) -> pd.DataFrame:
        """Exports ground-truth latent state trajectories for parameter recovery and identifiability studies."""
        rows = []
        for st in self.latent_states:
            rows.append(
                {
                    "patient_id": st.patient_id,
                    "day": st.day,
                    "b_loc": st.b_loc,
                    "b_bone": st.b_bone,
                    "b_liver": st.b_liver,
                    "b_lung": st.b_lung,
                    "b_brain": st.b_brain,
                    "total_burden": st.b_loc + st.b_bone + st.b_liver + st.b_lung + st.b_brain,
                    "m_ca153": st.m_ca153,
                    "m_cea": st.m_cea,
                    "o_liver": st.o_liver,
                    "o_bone": st.o_bone,
                    "o_renal": st.o_renal,
                    "is_indolent": st.is_indolent,
                    "treatment_active": st.treatment_active,
                    "mechanism_event_count": st.mechanism_event_count,
                }
            )
        return pd.DataFrame(rows)

    def get_unleaked_training_examples(
        self,
        horizon_days: float,
        use_observed_labels: bool | None = None,
    ) -> Tuple[pd.DataFrame, pd.Series]:
        """
        Extracts strictly un-leaked feature vectors X and prospective clinical event labels y.

        Parameters:
            horizon_days: Prospective prediction horizon window (e.g. 90, 180, 365 days).
            use_observed_labels: Required. True uses observed-diagnosis labels (partial verification);
                                 False uses latent ground-truth labels (synthetic oracle only).

        Unmeasured lab values are emitted as NaN, never as their simulator-side
        latent values. Outcomes censored before the horizon are NaN, not negative.
        For IPCW evaluation, use `get_survival_training_examples`, which also
        returns follow-up times and event codes.
        """
        X, y, _, _ = self.get_survival_training_examples(
            horizon_days=horizon_days, use_observed_labels=use_observed_labels
        )
        return X, y

    def get_survival_training_examples(
        self,
        horizon_days: float,
        use_observed_labels: bool | None = None,
    ) -> Tuple[pd.DataFrame, pd.Series, np.ndarray, np.ndarray]:
        """Build current-visit features and censor-aware outcomes.

        Event codes are 0=censored, 1=target event and 2=terminal competing event.
        Loss to follow-up is censoring, not a competing event. `y` is the
        selected target-by-horizon label and remains missing when the horizon is
        not observed. `use_observed_labels` is mandatory: True estimates observed
        diagnosis; False selects the synthetic oracle-only recurrence path.
        """
        if isinstance(horizon_days, (bool, np.bool_)) or not np.isscalar(horizon_days):
            raise ValueError("horizon_days must be a finite positive number, not boolean")
        try:
            horizon_days = float(horizon_days)
        except (TypeError, ValueError, OverflowError) as exc:
            raise ValueError("horizon_days must be finite and positive") from exc
        if not np.isfinite(horizon_days) or horizon_days <= 0:
            raise ValueError("horizon_days must be finite and positive")
        if not isinstance(use_observed_labels, (bool, np.bool_)):
            raise ValueError(
                "use_observed_labels must be explicitly set to True (observed diagnosis) "
                "or False (synthetic oracle truth)"
            )
        pt_map = {p.patient_id: p for p in self.patients}
        if len(pt_map) != len(self.patients):
            raise ValueError("patient_id values must be unique")
        last_observation_day: dict[str, float] = {}
        observed_days: dict[str, set[float]] = {}
        for item in self.observations:
            if item.patient_id not in pt_map:
                raise ValueError(f"observation references unknown patient_id {item.patient_id!r}")
            if not _is_finite_nonnegative_number(item.day):
                raise ValueError("observation days must be finite and non-negative")
            observation_day = float(item.day)
            patient_days = observed_days.setdefault(item.patient_id, set())
            if observation_day in patient_days:
                raise ValueError(
                    f"duplicate observation day for patient {item.patient_id}"
                )
            patient_days.add(observation_day)
            last_observation_day[item.patient_id] = max(
                last_observation_day.get(item.patient_id, -np.inf), observation_day
            )
        for patient_id, last_day in last_observation_day.items():
            patient = pt_map[patient_id]
            if not _is_finite_number(patient.age):
                raise ValueError(f"age must be finite numeric data for patient {patient_id}")
            if any(
                not isinstance(status, (bool, np.bool_))
                for status in (patient.er_status, patient.pr_status, patient.her2_status)
            ):
                raise ValueError(f"receptor status must be boolean for patient {patient_id}")
            if not isinstance(patient.stage, PresentationStage):
                raise ValueError(f"unsupported stage value for patient {patient_id}")
            recurrence_event = (
                patient.observed_recurrence_event
                if use_observed_labels
                else patient.true_recurrence_event
            )
            recurrence_day = (
                patient.observed_recurrence_day
                if use_observed_labels
                else patient.true_recurrence_day
            )
            competing_day = patient.competing_event_day
            if not isinstance(recurrence_event, (bool, np.bool_)):
                raise ValueError(
                    f"recurrence event flag must be boolean for patient {patient_id}"
                )
            if recurrence_event:
                if not _is_finite_nonnegative_number(recurrence_day):
                    raise ValueError(
                        f"recurrence event day must be finite and non-negative for patient {patient_id}"
                    )
            elif recurrence_day is not None and not pd.isna(recurrence_day):
                raise ValueError(
                    f"recurrence day supplied without an event for patient {patient_id}"
                )
            if patient.competing_event is None:
                if competing_day is not None and not pd.isna(competing_day):
                    raise ValueError(
                        f"competing event day supplied without an event for patient {patient_id}"
                    )
            elif (
                not isinstance(patient.competing_event, str)
                or patient.competing_event not in SUPPORTED_COMPETING_EVENTS
                or not _is_finite_nonnegative_number(competing_day)
            ):
                raise ValueError(
                    f"competing event type/day is invalid for patient {patient_id}"
                )
            if (
                recurrence_event
                and recurrence_day is not None
                and np.isfinite(recurrence_day)
                and competing_day is not None
                and np.isfinite(competing_day)
                and float(recurrence_day) == float(competing_day)
            ):
                raise ValueError(
                    f"recurrence and competing event share an ambiguous day for patient {patient_id}"
                )
            admin_end = patient.administrative_censor_day
            if admin_end is None or pd.isna(admin_end):
                admin_end = last_day
            if not _is_finite_nonnegative_number(admin_end) or float(admin_end) < last_day:
                raise ValueError(
                    f"observations extend beyond administrative follow-up for patient {patient_id}"
                )
            if (
                use_observed_labels
                and recurrence_event
                and recurrence_day is not None
                and float(recurrence_day) > float(admin_end)
            ):
                raise ValueError(
                    f"observed recurrence occurs after administrative follow-up for patient {patient_id}"
                )
            competing_day = patient.competing_event_day
            if competing_day is not None and np.isfinite(competing_day) and float(competing_day) < last_day:
                raise ValueError(
                    f"observations extend beyond a competing event for patient {patient_id}"
                )
        for obs in self.observations:
            if not isinstance(obs.analytes, dict) or not isinstance(obs.observed_mask, dict):
                raise ValueError("observation analytes and observed_mask must be mappings")
            analyte_codes = set(obs.analytes)
            if not analyte_codes.issubset(ANALYTE_REGISTRY):
                raise ValueError("observation contains an unregistered analyte code")
            if set(obs.observed_mask) != analyte_codes:
                raise ValueError("observed_mask keys must match observation analyte keys")
            for code, is_observed in obs.observed_mask.items():
                if not isinstance(is_observed, (bool, np.bool_)):
                    raise ValueError(f"observed_mask for {code} must be boolean")
                if is_observed and not _is_finite_number(obs.analytes[code]):
                    raise ValueError(
                        f"observed {code} measurement must be finite numeric data"
                    )
            if not isinstance(obs.symptoms, dict) or not set(obs.symptoms).issubset(
                TRACKED_SYMPTOMS
            ):
                raise ValueError("observation contains an unsupported symptom")
            for symptom, grade in obs.symptoms.items():
                if (
                    not _is_finite_number(grade)
                    or int(grade) != grade
                    or not 0 <= grade <= 4
                ):
                    raise ValueError(f"symptom grade for {symptom} must be an integer from 0 to 4")
            if obs.treatment_active is not None and (
                not isinstance(obs.treatment_active, str)
                or not obs.treatment_active.strip()
            ):
                raise ValueError("treatment_active must be a non-empty string or missing")
        features_list = []
        labels_list = []
        follow_up_times: list[float] = []
        event_codes: list[int] = []

        for obs in self.observations:
            pt = pt_map[obs.patient_id]

            # Select target event day based on observation regime
            if use_observed_labels:
                rec_event = pt.observed_recurrence_event
                rec_day = pt.observed_recurrence_day
            else:
                rec_event = pt.true_recurrence_event
                rec_day = pt.true_recurrence_day

            competing_day = pt.competing_event_day
            has_competing_day = competing_day is not None and np.isfinite(competing_day)
            loss_to_follow_up = pt.competing_event == "lost_to_follow_up"
            terminal_competing = has_competing_day and not loss_to_follow_up
            if competing_day is not None and np.isfinite(competing_day) and competing_day <= obs.day:
                continue

            if rec_event and rec_day is not None and np.isfinite(rec_day) and rec_day <= obs.day:
                # Already diagnosed before this landmark; it is not a prospective case.
                continue

            admin_end = pt.administrative_censor_day
            if admin_end is None or not np.isfinite(admin_end):
                admin_end = last_observation_day[pt.patient_id]
            censor_day = min(
                float(admin_end),
                float(competing_day)
                if loss_to_follow_up and competing_day is not None and np.isfinite(competing_day)
                else float(admin_end),
            )
            first_event_day: float | None = None
            event_code = 0
            if (
                rec_event
                and rec_day is not None
                and np.isfinite(rec_day)
                and rec_day <= censor_day
            ):
                first_event_day, event_code = float(rec_day), 1
            if terminal_competing and competing_day is not None and competing_day <= admin_end and (
                first_event_day is None or competing_day < first_event_day
            ):
                first_event_day, event_code = float(competing_day), 2
            end_day = first_event_day if first_event_day is not None else censor_day
            time_from_landmark = max(0.0, end_day - obs.day)
            if event_code == 1 and time_from_landmark <= horizon_days:
                y_label = 1.0
            elif event_code == 2 and time_from_landmark <= horizon_days:
                y_label = 0.0
            elif time_from_landmark >= horizon_days:
                y_label = 0.0
            else:
                y_label = float("nan")

            # Construct safe feature dict (strictly historical/current)
            feat: Dict[str, Any] = {
                "patient_id": obs.patient_id,
                "day": obs.day,
                "facility_id": obs.facility_id,
                "treatment_active": obs.treatment_active or "none",
                "age": pt.age,
                "is_er_pos": 1.0 if pt.er_status else 0.0,
                "is_pr_pos": 1.0 if pt.pr_status else 0.0,
                "is_her2_pos": 1.0 if pt.her2_status else 0.0,
                "is_stage_3_or_4": 1.0
                if pt.stage in [PresentationStage.STAGE_III, PresentationStage.STAGE_IV]
                else 0.0,
            }
            # Lab features (clean standardized naming)
            for k, v in obs.analytes.items():
                measured = bool(obs.observed_mask.get(k, False)) and np.isfinite(v)
                feat[f"lab_{k}"] = float(v) if measured else float("nan")
                feat[f"lab_{k}_observed"] = float(measured)
            # Symptom features
            for s, g in obs.symptoms.items():
                feat[f"sym_{s}"] = float(g)

            features_list.append(feat)
            labels_list.append(y_label)
            follow_up_times.append(time_from_landmark)
            event_codes.append(event_code)

        X = pd.DataFrame(features_list)
        target_estimand = (
            "observed_diagnosis" if use_observed_labels else "oracle_true_recurrence"
        )
        y = pd.Series(
            labels_list,
            name=f"{target_estimand}_within_{int(horizon_days)}d",
            dtype=float,
        )
        y.attrs["target_estimand"] = target_estimand
        y.attrs["horizon_days"] = float(horizon_days)
        y.attrs["synthetic_only"] = True
        return X, y, np.asarray(follow_up_times, dtype=float), np.asarray(event_codes, dtype=int)


