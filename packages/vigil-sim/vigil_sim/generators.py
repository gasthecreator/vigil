    def measurement_skip_probability(
        self, pt: PatientBaseline, analyte_code: str, _legacy_probability: float | None = None
    ) -> float:
        """Return the profile rate; keep the ignored legacy argument for call compatibility."""
        config = self.population_config["measurement_missingness"]
        if (self.get_generator_type() == GeneratorType.G1_SMOOTH
                and analyte_code in config["high_cost_analytes"]):
            probability = (
                float(config["high_cost_skip_probability_per_cost_factor"])
                * pt.out_of_pocket_delay_factor
            )
        else:
            probability = float(
                config["base_skip_probability_by_generator"][self.get_generator_type().value]
            )
        return float(np.clip(probability, 0.0, 1.0))

    def sample_baseline(self, patient_idx: int) -> PatientBaseline:
        """
        Samples an explicitly synthetic stress-test profile; not population-calibrated.
        """
        cfg = self.population_config
        pt_id = f"VIG-PT-{patient_idx:05d}"
        age_cfg = cfg["age_years"]
        if age_cfg["distribution"] == "uniform":
            age = float(self.rng.uniform(age_cfg["minimum"], age_cfg["maximum"]))
        elif age_cfg["distribution"] == "normal":
            age = float(np.clip(self.rng.normal(age_cfg["mean"], age_cfg["sd"]),
                                age_cfg["minimum"], age_cfg["maximum"]))
        else:
            raise ValueError(f"Unsupported age distribution: {age_cfg['distribution']}")
        stage_index = int(self.rng.choice(4, p=cfg["stage_probabilities"]))
        stage = list(PresentationStage)[stage_index]
        subtype_index = int(self.rng.choice(3, p=cfg["subtype_probabilities"]))
        subtype = list(BreastCancerSubtype)[subtype_index]
        receptor_cfg = cfg["receptor_probabilities"]
        if subtype == BreastCancerSubtype.TNBC:
            er = False
            pr = False
            her2 = False
        elif subtype == BreastCancerSubtype.HR_POS_HER2_NEG:
            er = True
            pr = bool(self.rng.random() < receptor_cfg["hr_positive_her2_negative_pr_positive"])
            her2 = False
        else:
            er = bool(self.rng.random() < receptor_cfg["her2_positive_er_positive"])
            pr = bool(self.rng.random() < receptor_cfg["her2_positive_pr_positive"])
            her2 = True

        p_rec = min(
            float(cfg["recurrence_cap_by_subtype"][subtype_index]),
            float(cfg["recurrence_probability_by_stage"][stage_index]
                  * cfg["recurrence_multiplier_by_subtype"][subtype_index]),
        )
        if not 0 <= p_rec <= 1:
            raise ValueError("Configured stage/subtype recurrence probability must be in [0, 1]")
        has_recurrence = bool(self.rng.random() < p_rec)

        # Indolent micro-metastatic course (overdetection modeling, ML_PROGRAM §4.5)
        # ~8% of recurrences grow extremely slowly and do not cause acute death in surveillance window
        is_indolent = False
        if has_recurrence and self.rng.random() < cfg["indolent_probability"]:
            is_indolent = True

        true_recurrence_day: Optional[float] = None
        true_recurrence_site: Optional[str] = None

        if has_recurrence:
            gamma_cfg = cfg["recurrence_time_gamma_by_subtype"][subtype_index]
            rec_days = float(self.rng.gamma(gamma_cfg["shape"], gamma_cfg["scale_days"])
                             + gamma_cfg["offset_days"])
            true_recurrence_day = min(float(cfg["recurrence_day_cap"]), rec_days)
            site_index = int(self.rng.choice(4, p=cfg["site_probabilities_by_subtype"][subtype_index]))
            true_recurrence_site = [TargetOrgan.BONE, TargetOrgan.LUNG,
                                    TargetOrgan.LIVER, TargetOrgan.BRAIN][site_index].value

        # Competing risks (intercurrent cardiovascular/septic death or loss-to-follow-up)
        competing_event: Optional[str] = None
        competing_event_day: Optional[float] = None
        comp_cfg = cfg["competing_event_probabilities"]
        comp_draw = self.rng.random()
        comp_cumulative = 0.0
        for event_name, probability in comp_cfg.items():
            comp_cumulative += float(probability)
            if comp_draw < comp_cumulative:
                competing_event = event_name
                time_range = cfg["competing_event_time_days"][event_name]
                competing_event_day = float(self.rng.uniform(*time_range))
                break

        # Facility parameters (inter-lab systematic analyzer bias and scale, Task T8)
        facility_effects = cfg["facility_lab_effects"]
        facility_count = int(facility_effects["facility_count"])
        facility_idx = int(self.rng.integers(1, facility_count + 1))
        facility_id = f"FACILITY-NG-{facility_idx:02d}"

        lab_offsets: Dict[str, float] = {}
        lab_scales: Dict[str, float] = {}
        if facility_id in self.facility_lab_effects:
            for code, (offset, scale) in self.facility_lab_effects[facility_id].items():
                lab_offsets[code], lab_scales[code] = offset, scale
        elif facility_effects["mode"] == "per_patient":
            for code in ANALYTE_REGISTRY:
                lab_offsets[code] = float(
                    self.rng.normal(0.0, facility_effects["offset_sd"])
                )
                lab_scales[code] = float(
                    self.rng.uniform(
                        facility_effects["scale_min"], facility_effects["scale_max"]
                    )
                )

        # Baseline analyte levels (inter-individual variation CVg centered at reference midpoint)
        # In adjuvant surveillance, patients entering monitoring have completed primary treatment
        # with no clinical evidence of disease (NED) and normal postoperative marker levels (Molina et al. 1995).
        # Baseline sampling settings are explicit synthetic profile assumptions.
        base_levels: Dict[str, float] = {}
        baseline_sampling = cfg["baseline_analyte_sampling"]
        for code, analyte in ANALYTE_REGISTRY.items():
            ref_mid = 0.5 * (
                analyte.plausibility.reference_low + analyte.plausibility.reference_high
            )
            sigma_g = min(
                baseline_sampling["between_patient_cv_cap"],
                analyte.biological_variation.cv_g / 100.0,
            )
            val = ref_mid * math.exp(float(self.rng.normal(-0.5 * sigma_g**2, sigma_g)))
            base_levels[code] = max(
                analyte.plausibility.reference_low
                * baseline_sampling["reference_low_fraction"],
                min(
                    analyte.plausibility.reference_high
                    * baseline_sampling["reference_high_fraction"],
                    val,
                ),
            )

        delay_range = cfg["out_of_pocket_delay_factor_range"]
        delay_factor = float(self.rng.uniform(*delay_range))

        return PatientBaseline(
            patient_id=pt_id,
            age=age,
            stage=stage,
            subtype=subtype,
            er_status=er,
            pr_status=pr,
            her2_status=her2,
            true_recurrence_event=has_recurrence,
            true_recurrence_day=true_recurrence_day,
            true_recurrence_site=true_recurrence_site,
            is_indolent=is_indolent,
            observed_recurrence_event=False,  # Updated dynamically during longitudinal simulation
            observed_recurrence_day=None,
            observed_recurrence_site=None,
            competing_event=competing_event,
            competing_event_day=competing_event_day,
            generator_id=self.get_generator_type().value,
            facility_id=facility_id,
            out_of_pocket_delay_factor=delay_factor,
            lab_offsets=lab_offsets,
            lab_scales=lab_scales,
            base_marker_levels=base_levels,
        )

    def generate_symptoms(
        self,
        pt: PatientBaseline,
        day: float,
        latent_state: LatentCompartmentState,
    ) -> Dict[str, int]:
        """
        Generates profile-configured symptom grades coupled to latent burden.
        """
        symptoms = dict.fromkeys(TRACKED_SYMPTOMS, 0)
        symptom_mechanics = self.population_config["symptom_mechanics"]
        baseline_symptoms = self.population_config["baseline_symptom_probabilities"]
        if self.rng.random() < baseline_symptoms["fatigue_weight_loss"]:
            symptoms["fatigue_weight_loss"] = symptom_mechanics["baseline_grade"]
        if self.rng.random() < baseline_symptoms["bone_pain"]:
            symptoms["bone_pain"] = symptom_mechanics["baseline_grade"]

        total_burden = (
            latent_state.b_loc
            + latent_state.b_bone
            + latent_state.b_liver
            + latent_state.b_lung
            + latent_state.b_brain
        )
        state_values = {
            "b_bone": latent_state.b_bone,
            "b_liver": latent_state.b_liver,
            "b_lung": latent_state.b_lung,
            "b_brain": latent_state.b_brain,
            "o_liver": latent_state.o_liver,
            "total_burden": total_burden,
        }
        for symptom, rule in symptom_mechanics["burden_rules"].items():
            if state_values[rule["trigger_state"]] <= rule["trigger_threshold"]:
                continue
            grade_value = state_values[rule["grade_state"]]
            if grade_value > rule["grade_threshold"]:
                grade = int(
                    min(
                        symptom_mechanics["maximum_grade"],
                        rule["grade_offset"] + round(grade_value / rule["grade_scale"]),
                    )
                )
                symptoms[symptom] = max(symptoms[symptom], grade)

        return symptoms

