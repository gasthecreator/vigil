class BaseCohortGenerator(ABC):
    """Abstract base class for all mechanistic cohort generators."""

    def __init__(self, seed: int = 42, population_config: Optional[Dict[str, Any]] = None):
        self.seed = seed
        self.rng = np.random.default_rng(seed)
        if population_config is None:
            config_path = Path(__file__).parent / "config" / "legacy_synthetic_population_v0.json"
            with config_path.open(encoding="utf-8") as config_file:
                population_config = json.load(config_file)
        self.population_config = population_config
        self._validate_population_config(population_config)
        self.generator_mechanics = population_config.get("generator_mechanics", {})
        self.facility_lab_effects: dict[str, dict[str, tuple[float, float]]] = {}
        facility_effects = population_config.get("facility_lab_effects")
        if facility_effects is not None:
            count = int(facility_effects["facility_count"])
            self.facility_lab_effects = {
                f"FACILITY-NG-{facility_idx:02d}": {
                    code: (
                        float(self.rng.normal(0.0, facility_effects["offset_sd"])),
                        float(self.rng.uniform(facility_effects["scale_min"], facility_effects["scale_max"])),
                    )
                    for code in ANALYTE_REGISTRY
                }
                for facility_idx in range(1, count + 1)
            }

    @staticmethod
    def _validate_population_config(config: Dict[str, Any]) -> None:
        """Reject malformed synthetic assumptions instead of silently normalizing them."""
        if not config.get("profile_id") or not config.get("interpretation"):
            raise ValueError("Population config requires profile_id and interpretation")
        if config["profile_id"] in {
            "balanced_synthetic_core_v3",
            "balanced_synthetic_core_v4",
        }:
            mechanics = config.get("generator_mechanics")
            if not isinstance(mechanics, dict) or not mechanics.get("provenance"):
                raise ValueError("balanced_synthetic_core_v3 requires documented generator_mechanics")
            required_paths = (
                "g1.lead_time_normal_days", "g1.lead_time_clip_days", "g1.seed_offset_days",
                "g1.growth_rate_by_group.indolent", "g1.growth_rate_by_group.tnbc",
                "g1.growth_rate_by_group.other", "g1.burden.exponent_cap",
                "g1.burden.mass_scale", "g1.burden.saturation_scale",
                "g1.secondary_compartment_fraction.bone_to_locoregional",
                "g1.secondary_compartment_fraction.liver_to_bone",
                "g1.marker_coupling.ca153_per_burden", "g1.marker_coupling.cea_per_burden",
                "g1.marker_coupling.ca153_site_multiplier.liver",
                "g1.marker_coupling.ca153_site_multiplier.bone",
                "g1.marker_coupling.ca153_site_multiplier.other",
                "g1.organ_damage.liver_per_liver_burden", "g1.organ_damage.bone_per_bone_burden",
                "g1.chemotherapy.eligible_stages", "g1.chemotherapy.assignment_probability",
                "g1.chemotherapy.active_days", "g1.chemotherapy.liver_stress",
                "g1.chemotherapy.myelosuppression_multiplier", "g1.chemotherapy.hemoglobin_reduction",
                "g1.enzyme_coupling.alt_ast_per_liver_damage",
                "g1.enzyme_coupling.alp_ggt_per_liver_damage",
                "g1.enzyme_coupling.alp_ggt_per_bone_damage",
                "g1.enzyme_coupling.bilirubin_liver_damage_threshold",
                "g1.enzyme_coupling.bilirubin_per_excess_liver_damage",
                "g1.enzyme_coupling.calcium_bone_damage_threshold",
                "g1.enzyme_coupling.calcium_per_excess_bone_damage",
                "g2.burst_count_exclusive_range", "g2.days_before_recurrence_range",
                "g2.apply_facility_lab_effects",
                "g2.recent_burst_window_days", "g2.burden_per_burst", "g2.ca153_per_burden",
                "g2.ca153_recent_burst_increment", "g2.cea_per_burden",
                "g2.cea_recent_burst_increment", "g2.liver_damage_per_liver_burden",
                "g2.bone_damage_per_bone_burden", "g2.liver_enzyme_per_damage",
                "g2.alp_per_bone_damage", "g3.haemolysis_probability",
                "g3.sample_dilution_probability", "g3.active_signal_days",
                "g3.burden_at_full_signal", "g3.ca153_per_burden", "g3.cea_per_burden",
                "g3.liver_damage_per_liver_burden", "g3.bone_damage_per_bone_burden",
                "g3.student_t_degrees_freedom", "g3.student_t_noise_scale",
                "g3.ca153_signal_increment", "g3.alt_liver_signal_increment",
                "g3.alp_bone_signal_increment", "g3.haemolysis_ast_multiplier",
                "g3.haemolysis_ldh_multiplier", "g3.sample_dilution_multiplier",
                "g3.apply_facility_lab_effects",
                "g3.saturate_signal",
            )
            legacy_only_v4 = {
                "g1.marker_coupling.ca153_per_burden",
                "g1.marker_coupling.cea_per_burden",
                "g2.burst_count_exclusive_range",
                "g2.days_before_recurrence_range",
                "g2.recent_burst_window_days",
                "g2.burden_per_burst",
                "g2.ca153_recent_burst_increment",
                "g2.cea_recent_burst_increment",
            }
            for path in required_paths:
                if config["profile_id"] == "balanced_synthetic_core_v4" and path in legacy_only_v4:
                    continue
                value: Any = mechanics
                for key in path.split("."):
                    if not isinstance(value, dict) or key not in value:
                        raise ValueError(f"generator_mechanics is missing required setting: {path}")
                    value = value[key]
                if value is None:
                    raise ValueError(f"generator_mechanics.{path} may not be null")
                if isinstance(value, (int, float)) and not np.isfinite(value):
                    raise ValueError(f"generator_mechanics.{path} must be finite")
                if isinstance(value, (list, tuple)) and value:
                    array = np.asarray(value)
                    if array.dtype.kind in "iuf" and not np.isfinite(array.astype(float)).all():
                        raise ValueError(f"generator_mechanics.{path} must be finite")
                    if array.dtype.kind in "iuf" and np.any(array.astype(float) < 0):
                        raise ValueError(f"generator_mechanics.{path} must be non-negative")
                if isinstance(value, (int, float)) and value < 0:
                    raise ValueError(f"generator_mechanics.{path} must be non-negative")
            for path in (
                "g1.lead_time_clip_days",
                "g1.growth_rate_by_group.indolent", "g1.growth_rate_by_group.tnbc",
                "g1.growth_rate_by_group.other", "g1.chemotherapy.active_days",
                "g1.chemotherapy.liver_stress", "g1.chemotherapy.myelosuppression_multiplier",
                "g1.chemotherapy.hemoglobin_reduction", "g2.burst_count_exclusive_range",
                "g2.days_before_recurrence_range", "g3.haemolysis_ast_multiplier",
                "g3.haemolysis_ldh_multiplier", "g3.sample_dilution_multiplier",
            ):
                if config["profile_id"] == "balanced_synthetic_core_v4" and path in legacy_only_v4:
                    continue
                value = mechanics
                for key in path.split("."):
                    value = value[key]
                if len(value) != 2 or value[0] >= value[1]:
                    raise ValueError(f"generator_mechanics.{path} must be an increasing pair")
            lead_distribution = mechanics["g1"]["lead_time_normal_days"]
            if len(lead_distribution) != 2 or lead_distribution[1] <= 0:
                raise ValueError("generator_mechanics.g1.lead_time_normal_days must be mean and positive SD")
            if sum(
                mechanics["g3"][key]
                for key in ("haemolysis_probability", "sample_dilution_probability")
            ) > 1:
                raise ValueError("g3 pre-analytical error probabilities may not sum above one")
            for setting in (
                mechanics["g2"]["apply_facility_lab_effects"],
                mechanics["g3"]["apply_facility_lab_effects"],
                mechanics["g3"]["saturate_signal"],
            ):
                if not isinstance(setting, bool):
                    raise ValueError("generator_mechanics switches must be boolean")
            probability_values = (
                mechanics["g1"]["chemotherapy"]["assignment_probability"],
                mechanics["g3"]["haemolysis_probability"],
                mechanics["g3"]["sample_dilution_probability"],
            )
            if any(not 0 <= probability <= 1 for probability in probability_values):
                raise ValueError("generator_mechanics probabilities must be in [0, 1]")
            if (
                mechanics["g1"]["burden"]["saturation_scale"] <= 0
                or mechanics["g3"]["active_signal_days"] <= 0
                or mechanics["g3"]["student_t_degrees_freedom"] <= 0
            ):
                raise ValueError("generator_mechanics scales and Student-t degrees of freedom must be positive")
            if config["profile_id"] == "balanced_synthetic_core_v4":
                g1_kinetics = mechanics["g1"].get("marker_kinetics", {})
                g2_shot_noise = mechanics["g2"].get("shot_noise", {})
                required_kinetics = (
                    "integration_step_days", "ca153_secretion_per_burden_day",
                    "ca153_clearance_rate_per_day", "cea_secretion_per_burden_day",
                    "cea_clearance_rate_per_day",
                )
                required_shot_noise = (
                    "event_rate_per_day", "burden_amplitude_mean",
                    "burden_amplitude_coefficient_of_variation",
                    "ca153_clearance_rate_per_day", "cea_clearance_rate_per_day",
                )
                for name, settings, required in (
                    ("g1.marker_kinetics", g1_kinetics, required_kinetics),
                    ("g2.shot_noise", g2_shot_noise, required_shot_noise),
                ):
                    for key in required:
                        value = settings.get(key)
                        if not isinstance(value, (int, float)) or not np.isfinite(value):
                            raise ValueError(f"{name}.{key} must be finite")
                        if value < 0 or (("clearance_rate" in key or key == "integration_step_days") and value == 0):
                            raise ValueError(f"{name}.{key} must be positive")
                if g2_shot_noise["burden_amplitude_mean"] == 0:
                    raise ValueError("g2.shot_noise.burden_amplitude_mean must be positive")
        age = config["age_years"]
        if not (0 < age["minimum"] < age["maximum"]):
            raise ValueError("age_years must define a positive, increasing range")
        if age.get("distribution") not in {"uniform", "normal"}:
            raise ValueError("age_years distribution must be uniform or normal")
        if age["distribution"] == "normal" and not (
            np.isfinite(age.get("mean", np.nan))
            and np.isfinite(age.get("sd", np.nan))
            and age["sd"] > 0
        ):
            raise ValueError("normal age_years requires finite mean and positive sd")
        for key, expected in (("stage_probabilities", 4), ("subtype_probabilities", 3)):
            probabilities = np.asarray(config[key], dtype=float)
            if (len(probabilities) != expected or not np.isfinite(probabilities).all()
                    or np.any(probabilities < 0) or not np.isclose(probabilities.sum(), 1.0)):
                raise ValueError(f"{key} must contain {expected} probabilities summing to one")
        site_probs = np.asarray(config["site_probabilities_by_subtype"], dtype=float)
        if (site_probs.shape != (3, 4) or not np.isfinite(site_probs).all()
                or np.any(site_probs < 0) or not np.allclose(site_probs.sum(axis=1), 1.0)):
            raise ValueError("site_probabilities_by_subtype must be three distributions over four sites")
        for key in ("indolent_probability", *config["competing_event_probabilities"]):
            probability = (config[key] if key == "indolent_probability"
                           else config["competing_event_probabilities"][key])
            if not 0 <= float(probability) <= 1:
                raise ValueError(f"{key} must be a probability")
        if sum(config["competing_event_probabilities"].values()) > 1:
            raise ValueError("Competing event probabilities may not sum above one")
        for event_name, bounds in config["competing_event_time_days"].items():
            if (len(bounds) != 2 or not np.isfinite(bounds).all()
                    or not 0 <= bounds[0] < bounds[1]):
                raise ValueError(f"Invalid competing event time range for {event_name}")
        if set(config["competing_event_probabilities"]) != set(config["competing_event_time_days"]):
            raise ValueError("Every competing event probability needs a matching time range")
        facility_effects = config.get("facility_lab_effects")
        if facility_effects is not None:
            if (int(facility_effects.get("facility_count", 0)) < 2
                    or not np.isfinite(facility_effects.get("offset_sd", np.nan))
                    or facility_effects["offset_sd"] < 0
                    or not 0 < facility_effects.get("scale_min", 0)
                    or facility_effects["scale_min"] >= facility_effects.get("scale_max", 0)):
                raise ValueError("facility_lab_effects must define count, offset_sd, and increasing positive scale bounds")
        verification = config.get("verification")
        if verification is not None:
            for key in ("sensitivity", "specificity"):
                if not np.isfinite(verification.get(key, np.nan)) or not 0 <= verification[key] <= 1:
                    raise ValueError(f"verification.{key} must be in [0, 1]")
            if (not np.isfinite(verification.get("visible_burden_threshold", np.nan))
                    or verification["visible_burden_threshold"] < 0):
                raise ValueError("verification.visible_burden_threshold must be finite and non-negative")
            if (not 0 <= verification.get("routine_imaging_probability", -1) <= 1
                    or not 0 <= verification.get("maximum_imaging_probability", -1) <= 1):
                raise ValueError("verification imaging probabilities must be in [0, 1]")
            for threshold_key, increment_key in (
                ("symptom_grade_thresholds", "symptom_probability_increments"),
                ("marker_thresholds", "marker_probability_increments"),
            ):
                thresholds = verification.get(threshold_key, [])
                increments = verification.get(increment_key, [])
                if (len(thresholds) != 2 or len(increments) != 2
                        or not np.isfinite(thresholds).all()
                        or not np.isfinite(increments).all()
                        or thresholds[0] >= thresholds[1]
                        or np.any(np.asarray(increments) < 0)):
                    raise ValueError(f"verification.{threshold_key} and {increment_key} are malformed")
        missingness = config.get("measurement_missingness")
        if missingness is not None:
            for generator_type in GeneratorType:
                probability = missingness.get("base_skip_probability_by_generator", {}).get(
                    generator_type.value
                )
                if probability is None or not np.isfinite(probability) or not 0 <= probability <= 1:
                    raise ValueError("measurement_missingness requires a valid skip probability for each generator")
            if (not np.isfinite(missingness.get("high_cost_skip_probability_per_cost_factor", np.nan))
                    or not 0 <= missingness["high_cost_skip_probability_per_cost_factor"] <= 1):
                raise ValueError("measurement_missingness high-cost skip rate must be in [0, 1]")
            if not missingness.get("high_cost_analytes"):
                raise ValueError("measurement_missingness requires high_cost_analytes")
        baseline_symptoms = config.get("baseline_symptom_probabilities")
        if baseline_symptoms is not None and any(
            not np.isfinite(baseline_symptoms.get(key, np.nan))
            or not 0 <= baseline_symptoms[key] <= 1
            for key in ("fatigue_weight_loss", "bone_pain")
        ):
            raise ValueError("baseline_symptom_probabilities must define probabilities in [0, 1]")
        delay_range = config.get("out_of_pocket_delay_factor_range")
        if delay_range is not None and (
            len(delay_range) != 2 or not np.isfinite(delay_range).all()
            or not 0 < delay_range[0] <= delay_range[1]
        ):
            raise ValueError("out_of_pocket_delay_factor_range must be positive, finite, and increasing")
        visit_gamma = config.get("visit_interval_gamma")
        if visit_gamma is not None and (
            not np.isfinite(visit_gamma.get("shape", np.nan))
            or not np.isfinite(visit_gamma.get("scale", np.nan))
            or visit_gamma["shape"] <= 0 or visit_gamma["scale"] <= 0
        ):
            raise ValueError("visit_interval_gamma shape and scale must be positive and finite")
        if len(config["recurrence_time_gamma_by_subtype"]) != 3:
            raise ValueError("recurrence_time_gamma_by_subtype must match the three subtypes")
        if len(config["recurrence_multiplier_by_subtype"]) != 3:
            raise ValueError("recurrence_multiplier_by_subtype must match the three subtypes")
        for key in (
            "recurrence_probability_by_stage",
            "recurrence_multiplier_by_subtype",
            "recurrence_cap_by_subtype",
        ):
            values = np.asarray(config[key], dtype=float)
            expected = 4 if key == "recurrence_probability_by_stage" else 3
            if len(values) != expected or not np.isfinite(values).all() or np.any(values < 0):
                raise ValueError(f"{key} must contain {expected} finite non-negative values")
        if np.any(np.asarray(config["recurrence_probability_by_stage"], dtype=float) > 1):
            raise ValueError("Stage recurrence probabilities must be in [0, 1]")
        if np.any(np.asarray(config["recurrence_cap_by_subtype"], dtype=float) > 1):
            raise ValueError("Recurrence caps must be in [0, 1]")
        for item in config["recurrence_time_gamma_by_subtype"]:
            if not all(np.isfinite(item.get(key, np.nan)) for key in ("shape", "scale_days", "offset_days")):
                raise ValueError("Recurrence gamma parameters must be finite")
            if item["shape"] <= 0 or item["scale_days"] <= 0 or item["offset_days"] < 0:
                raise ValueError("Recurrence gamma shape/scale must be positive and offset non-negative")
        if not np.isfinite(config["recurrence_day_cap"]) or config["recurrence_day_cap"] <= 0:
            raise ValueError("recurrence_day_cap must be positive and finite")

    def measurement_skip_probability(
        self, pt: PatientBaseline, analyte_code: str, legacy_probability: float
    ) -> float:
        """Return the registered synthetic missingness probability for one assay."""
        config = self.population_config.get("measurement_missingness")
        if config is None:
            return float(np.clip(legacy_probability, 0.0, 1.0))
        if (self.get_generator_type() == GeneratorType.G1_SMOOTH
                and analyte_code in config["high_cost_analytes"]):
            probability = (
                float(config["high_cost_skip_probability_per_cost_factor"])
                * pt.out_of_pocket_delay_factor
            )
        else:
            probability = float(
                config["base_skip_probability_by_generator"][self.get_generator_type().value]
            )
        return float(np.clip(probability, 0.0, 1.0))

    def sample_baseline(self, patient_idx: int) -> PatientBaseline:
        """
        Samples an explicitly synthetic stress-test profile; not population-calibrated.
        """
        cfg = self.population_config
        pt_id = f"VIG-PT-{patient_idx:05d}"
        age_cfg = cfg["age_years"]
        if age_cfg["distribution"] == "uniform":
            age = float(self.rng.uniform(age_cfg["minimum"], age_cfg["maximum"]))
        elif age_cfg["distribution"] == "normal":
            age = float(np.clip(self.rng.normal(age_cfg["mean"], age_cfg["sd"]),
                                age_cfg["minimum"], age_cfg["maximum"]))
        else:
            raise ValueError(f"Unsupported age distribution: {age_cfg['distribution']}")
        stage_index = int(self.rng.choice(4, p=cfg["stage_probabilities"]))
        stage = list(PresentationStage)[stage_index]
        subtype_index = int(self.rng.choice(3, p=cfg["subtype_probabilities"]))
        subtype = list(BreastCancerSubtype)[subtype_index]
        receptor_cfg = cfg["receptor_probabilities"]
        if subtype == BreastCancerSubtype.TNBC:
            er = False
            pr = False
            her2 = False
        elif subtype == BreastCancerSubtype.HR_POS_HER2_NEG:
            er = True
            pr = bool(self.rng.random() < receptor_cfg["hr_positive_her2_negative_pr_positive"])
            her2 = False
        else:
            er = bool(self.rng.random() < receptor_cfg["her2_positive_er_positive"])
            pr = bool(self.rng.random() < receptor_cfg["her2_positive_pr_positive"])
            her2 = True

        p_rec = min(
            float(cfg["recurrence_cap_by_subtype"][subtype_index]),
            float(cfg["recurrence_probability_by_stage"][stage_index]
                  * cfg["recurrence_multiplier_by_subtype"][subtype_index]),
        )
        if not 0 <= p_rec <= 1:
            raise ValueError("Configured stage/subtype recurrence probability must be in [0, 1]")
        has_recurrence = bool(self.rng.random() < p_rec)

        # Indolent micro-metastatic course (overdetection modeling, ML_PROGRAM §4.5)
        # ~8% of recurrences grow extremely slowly and do not cause acute death in surveillance window
        is_indolent = False
        if has_recurrence and self.rng.random() < cfg["indolent_probability"]:
            is_indolent = True

        true_recurrence_day: Optional[float] = None
        true_recurrence_site: Optional[str] = None

        if has_recurrence:
            gamma_cfg = cfg["recurrence_time_gamma_by_subtype"][subtype_index]
            rec_days = float(self.rng.gamma(gamma_cfg["shape"], gamma_cfg["scale_days"])
                             + gamma_cfg["offset_days"])
            true_recurrence_day = min(float(cfg["recurrence_day_cap"]), rec_days)
            site_index = int(self.rng.choice(4, p=cfg["site_probabilities_by_subtype"][subtype_index]))
            true_recurrence_site = [TargetOrgan.BONE, TargetOrgan.LUNG,
                                    TargetOrgan.LIVER, TargetOrgan.BRAIN][site_index].value

        # Competing risks (intercurrent cardiovascular/septic death or loss-to-follow-up)
        competing_event: Optional[str] = None
        competing_event_day: Optional[float] = None
        comp_cfg = cfg["competing_event_probabilities"]
        comp_draw = self.rng.random()
        comp_cumulative = 0.0
        for event_name, probability in comp_cfg.items():
            comp_cumulative += float(probability)
            if comp_draw < comp_cumulative:
                competing_event = event_name
                time_range = cfg["competing_event_time_days"][event_name]
                competing_event_day = float(self.rng.uniform(*time_range))
                break

        # Facility parameters (inter-lab systematic analyzer bias and scale, Task T8)
        facility_count = int(cfg.get("facility_lab_effects", {}).get("facility_count", 6))
        facility_idx = int(self.rng.integers(1, facility_count + 1))
        facility_id = f"FACILITY-NG-{facility_idx:02d}"

        lab_offsets: Dict[str, float] = {}
        lab_scales: Dict[str, float] = {}
        if facility_id in self.facility_lab_effects:
            for code, (offset, scale) in self.facility_lab_effects[facility_id].items():
                lab_offsets[code], lab_scales[code] = offset, scale
        else:
            # Legacy profile behavior, retained for historical experiment compatibility.
            for code in ANALYTE_REGISTRY:
                lab_offsets[code] = float(self.rng.normal(0.0, 0.06))
                lab_scales[code] = float(self.rng.uniform(0.94, 1.06))

        # Baseline analyte levels (inter-individual variation CVg centered at reference midpoint)
        # In adjuvant surveillance, patients entering monitoring have completed primary treatment
        # with no clinical evidence of disease (NED) and normal postoperative marker levels (Molina et al. 1995).
        # General unselected population CVg is conditioned to the disease-free remission distribution (sigma_g <= 0.22).
        base_levels: Dict[str, float] = {}
        for code, analyte in ANALYTE_REGISTRY.items():
            ref_mid = 0.5 * (
                analyte.plausibility.reference_low + analyte.plausibility.reference_high
            )
            sigma_g = min(0.22, analyte.biological_variation.cv_g / 100.0)
            val = ref_mid * math.exp(float(self.rng.normal(-0.5 * sigma_g**2, sigma_g)))
            base_levels[code] = max(
                analyte.plausibility.reference_low * 0.8,
                min(analyte.plausibility.reference_high * 0.95, val),
            )

        delay_range = cfg.get("out_of_pocket_delay_factor_range", [1.0, 2.4])
        delay_factor = float(self.rng.uniform(*delay_range))

        return PatientBaseline(
            patient_id=pt_id,
            age=age,
            stage=stage,
            subtype=subtype,
            er_status=er,
            pr_status=pr,
            her2_status=her2,
            true_recurrence_event=has_recurrence,
            true_recurrence_day=true_recurrence_day,
            true_recurrence_site=true_recurrence_site,
            is_indolent=is_indolent,
            observed_recurrence_event=False,  # Updated dynamically during longitudinal simulation
            observed_recurrence_day=None,
            observed_recurrence_site=None,
            competing_event=competing_event,
            competing_event_day=competing_event_day,
            generator_id=self.get_generator_type().value,
            facility_id=facility_id,
            out_of_pocket_delay_factor=delay_factor,
            lab_offsets=lab_offsets,
            lab_scales=lab_scales,
            base_marker_levels=base_levels,
        )

    def generate_symptoms(
        self,
        pt: PatientBaseline,
        day: float,
        latent_state: LatentCompartmentState,
    ) -> Dict[str, int]:
        """
        Generates realistic symptom grades (0 to 4) coupled to organ burdens.
        """
        symptoms = {
            "bone_pain": 0,
            "jaundice": 0,
            "ruq_pain": 0,
            "cough_dyspnea": 0,
            "headache_neuro": 0,
            "fatigue_weight_loss": 0,
        }

        # Non-specific baseline symptoms
        baseline_symptoms = self.population_config.get("baseline_symptom_probabilities", {})
        if self.rng.random() < baseline_symptoms.get("fatigue_weight_loss", 0.08):
            symptoms["fatigue_weight_loss"] = 1
        if self.rng.random() < baseline_symptoms.get("bone_pain", 0.04):
            symptoms["bone_pain"] = 1

        # Couple symptoms directly to latent compartment burdens
        if latent_state.b_bone > 5.0:
            grade = int(min(4, 1 + round(latent_state.b_bone / 15.0)))
            symptoms["bone_pain"] = max(symptoms["bone_pain"], grade)

        if latent_state.b_liver > 5.0:
            grade = int(min(4, 1 + round(latent_state.b_liver / 15.0)))
            symptoms["ruq_pain"] = max(symptoms["ruq_pain"], grade)
            if latent_state.o_liver > 25.0:
                symptoms["jaundice"] = int(min(4, round(latent_state.o_liver / 20.0)))

        if latent_state.b_lung > 8.0:
            grade = int(min(4, 1 + round(latent_state.b_lung / 18.0)))
            symptoms["cough_dyspnea"] = max(symptoms["cough_dyspnea"], grade)

        if latent_state.b_brain > 3.0:
            grade = int(min(4, 1 + round(latent_state.b_brain / 10.0)))
            symptoms["headache_neuro"] = max(symptoms["headache_neuro"], grade)

        # High systemic burden causes cancer cachexia / fatigue
        total_burden = (
            latent_state.b_loc
            + latent_state.b_bone
            + latent_state.b_liver
            + latent_state.b_lung
            + latent_state.b_brain
        )
        if total_burden > 20.0:
            symptoms["fatigue_weight_loss"] = int(min(4, 2 + round(total_burden / 30.0)))

        return symptoms

